// ============================================================================
// File Writing
// ============================================================================

/**
 * Write a deployment file to disk, creating parent directories as needed.
 */
function writeDeploymentFile(absPath: string, content: string): void {
  const dir = absPath.substring(0, absPath.lastIndexOf('/'));
  mkdirSync(dir, { recursive: true, mode: DIR_MODE });
  try {
    writeFileSync(absPath, content, { encoding: 'utf-8', mode: FILE_MODE });
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : String(err);
    throw new Error(`ECLI-P4-071: Failed to write deployment file ${absPath}: ${message}`);
  }
}


/**
 * Generate a multi-stage Dockerfile for a TypeScript / Node 20 service.
 * Cloud-agnostic -- works on any container runtime.
 */
function tsDockerfile(): string {
  return [
    '# Generated by Phase 4 pipeline — do not edit manually',
    '',
    '# Stage 1: build',
    'FROM node:20-slim AS builder',
    'WORKDIR /app',
    'COPY package*.json ./',
    'RUN npm ci',
    'COPY . .',
    'RUN npm run build',
    '',
    '# Stage 2: runtime',
    'FROM node:20-slim',
    'WORKDIR /app',
    'ENV NODE_ENV=production',
    'COPY --from=builder /app/dist ./dist',
    'COPY --from=builder /app/node_modules ./node_modules',
    'EXPOSE 8080',
    'USER node',
    'CMD ["node", "dist/server/main.js"]',
    '',
  ].join('\n');
}

/**
 * Generate a multi-stage Dockerfile for a Rust / Axum service.
 * Cloud-agnostic -- works on any container runtime.
 */
function rustDockerfile(): string {
  return [
    '# Generated by Phase 4 pipeline — do not edit manually',
    '',
    '# Stage 1: build',
    'FROM rust:1.77 AS builder',
    'WORKDIR /app',
    'COPY Cargo.toml Cargo.lock ./',
    'COPY src ./src',
    'RUN cargo build --release',
    '',
    '# Stage 2: runtime (minimal debian image)',
    'FROM debian:bookworm-slim',
    'RUN apt-get update && apt-get install -y --no-install-recommends \\',
    '    ca-certificates \\',
    '    && rm -rf /var/lib/apt/lists/*',
    'RUN groupadd -r appuser && useradd -r -g appuser appuser',
    'COPY --from=builder /app/target/release/server /usr/local/bin/server',
    'EXPOSE 8080',
    'USER appuser',
    'CMD ["server"]',
    '',
  ].join('\n');
}


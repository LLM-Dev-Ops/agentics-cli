/**
 * Phase 4 Pipeline -- Stage 7: Deployment Generator
 *
 * Generates cloud-provider-specific deployment descriptors based on the
 * cloudProvider field in ERPResolution:
 *
 *   gcp (default)  -- Cloud Run: Knative YAML, Cloud Build, GCP .env.example
 *   aws            -- ECS/Fargate: task-definition.json, buildspec.yml, AWS .env.example
 *   azure          -- Container Apps: container-app.yaml, azure-pipelines.yml, Azure .env.example
 *   alibaba/on-prem -- Dockerfile + generic .env.example (no orchestrator-specific files)
 *
 * The Dockerfile is cloud-agnostic and shared across all providers.
 *
 * TypeScript target: Node 20 multi-stage Docker build.
 * Rust target: Rust 1.77 / Debian bookworm-slim multi-stage Docker build.
 *
 * All generated files carry a "do not edit manually" header.
 *
 * Exports:
 *   - generateDeployment(context) -- pipeline entry point
 *
 * Error codes:
 *   ECLI-P4-070  Missing prerequisite stage output (erp-target-resolution)
 *   ECLI-P4-071  Deployment file write failure
 */


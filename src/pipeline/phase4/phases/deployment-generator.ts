/**
 * Stage 7 entry point: generate cloud-provider-specific deployment descriptors.
 *
 * Reads ERPResolution from context.stageOutputs.get('erp-target-resolution'),
 * checks cloudProvider to determine which deployment templates to generate,
 * derives a short trace ID suffix, and writes all deployment files to
 * phase4/deployment/.
 *
 * Supported providers:
 *   - gcp (default): Cloud Run + Cloud Build
 *   - aws: ECS/Fargate + CodeBuild
 *   - azure: Container Apps + Azure DevOps Pipelines
 *   - alibaba, on-prem: Dockerfile + generic .env.example
 *
 * @param context - The Phase 4 pipeline context
 * @returns Stage output describing success or failure
 */
export function generateDeployment(context: Phase4Context): Phase4StageOutput {
  const startTime = Date.now();
  const rootSpan = createSpan('deployment-generation', 'generate-deployment', {
    phase4Dir: context.phase4Dir,
    traceId: context.traceId,
  });

  try {
    // Verify ERP target resolution completed
    const erpStage = context.stageOutputs.get('erp-target-resolution');
    if (!erpStage || erpStage.status !== 'completed') {
      throw new Error(
        'ECLI-P4-070: ERP target resolution not available on context. ' +
        'Ensure the erp-target-resolution stage completed successfully before running deployment-generation.',
      );
    }
    const erpResolution = erpStage.data as ERPResolution;
    const cloudProvider: CloudProvider = erpResolution.cloudProvider ?? 'gcp';

    // Resolve implementation language and short trace ID
    const language = context.phase3Artifacts.implementationLanguage;

    // Non-TS/Rust languages handled by Ruflo swarm
    if (!hasTemplateSupport(language)) {
      const span = endSpan(rootSpan, 'ok', { delegated: true, language });
      emitSpan(span);
      return {
        stage: 'deployment-generation',
        status: 'completed',
        data: { files: [], cloudRunService: 'delegated-to-ruflo' } satisfies DeploymentOutput,
        artifacts: [],
        timing: Date.now() - startTime,
        summary: `Deployment for ${language} delegated to Ruflo swarm.`,
      };
    }

    const traceIdShort = context.traceId.slice(0, 8);
    const isTs = language === 'typescript';

    // Output directory: phase4/deployment/
    const deployDir = join(context.phase4Dir, 'deployment');
    mkdirSync(deployDir, { recursive: true, mode: DIR_MODE });

    const deployFiles: DeploymentFile[] = [];
    const writtenPaths: string[] = [];

    const genSpan = createSpan(
      'deployment-generation',
      'generate-files',
      { language, traceIdShort, cloudProvider },
      rootSpan.spanId,
    );

    // Dockerfile (language-specific, cloud-agnostic)
    const dockerfileContent = isTs ? tsDockerfile() : rustDockerfile();
    const dockerfilePath = join(deployDir, 'Dockerfile');
    writeDeploymentFile(dockerfilePath, dockerfileContent);
    deployFiles.push({ relativePath: 'deployment/Dockerfile', content: dockerfileContent, kind: 'deployment' });
    writtenPaths.push(dockerfilePath);

    // Provider-specific deployment files
    let providerFiles: Array<{ relativePath: string; content: string }>;
    switch (cloudProvider) {
      case 'aws':
        providerFiles = generateAwsFiles(deployDir, traceIdShort);
        break;
      case 'azure':
        providerFiles = generateAzureFiles(deployDir, traceIdShort);
        break;
      case 'alibaba':
      case 'on-prem':
        providerFiles = generateGenericFiles(deployDir, traceIdShort);
        break;
      case 'gcp':
      default:
        providerFiles = generateGcpFiles(deployDir, traceIdShort);
        break;
    }

    // Kubernetes manifests — generated for all providers (K8s is universal)
    const k8sFiles = generateK8sFiles(deployDir, traceIdShort);
    for (const kf of k8sFiles) {
      const fileName = kf.relativePath.replace('deployment/', '');
      const absPath = join(deployDir, fileName);
      writeDeploymentFile(absPath, kf.content);
      deployFiles.push({ relativePath: kf.relativePath, content: kf.content, kind: 'deployment' });
      writtenPaths.push(absPath);
    }

    for (const pf of providerFiles) {
      const fileName = pf.relativePath.replace('deployment/', '');
      const absPath = join(deployDir, fileName);
      writeDeploymentFile(absPath, pf.content);
      deployFiles.push({ relativePath: pf.relativePath, content: pf.content, kind: 'deployment' });
      writtenPaths.push(absPath);
    }

    const serviceName = `mvp-${traceIdShort}`;

    // ADR-063: Copy essential deployment files into project/ so they travel with the code
    const projectDir = join(context.phase4Dir, 'project');
    try {
      mkdirSync(projectDir, { recursive: true, mode: DIR_MODE });

      // Dockerfile at project root
      const projectDockerfilePath = join(projectDir, 'Dockerfile');
      // Check if Rust optimizer exists — generate multi-stage Dockerfile
      const hasRustOptimizer = /\brust\b/i.test(context.scenarioQuery) &&
        /graph|optim|simul|network|dependency|pareto|compute/i.test(context.scenarioQuery);
      const finalDockerfile = hasRustOptimizer ? [
        '# Generated by Phase 4 pipeline — do not edit manually',
        '',
        '# Stage 1: Build Rust optimizer engine',
        'FROM rust:1.77-slim AS rust-builder',
        'WORKDIR /app/optimizer-engine',
        'COPY optimizer-engine/ .',
        'RUN cargo build --release',
        '',
        '# Stage 2: Build TypeScript',
        'FROM node:20-slim AS ts-builder',
        'WORKDIR /app',
        'COPY package*.json ./',
        'RUN npm ci',
        'COPY tsconfig.json ./',
        'COPY src/ src/',
        'RUN npm run build',
        '',
        '# Stage 3: Production runtime',
        'FROM node:20-slim',
        'WORKDIR /app',
        'ENV NODE_ENV=production',
        'COPY --from=ts-builder /app/dist ./dist',
        'COPY --from=ts-builder /app/node_modules ./node_modules',
        'COPY --from=rust-builder /app/optimizer-engine/target/release/*-optimizer ./optimizer-engine/target/release/',
        'COPY package.json ./',
        'EXPOSE 8080',
        'USER node',
        'CMD ["node", "dist/server/main.js"]',
        '',
      ].join('\n') : dockerfileContent;
      writeFileSync(projectDockerfilePath, finalDockerfile, { encoding: 'utf-8', mode: FILE_MODE });
      writtenPaths.push(projectDockerfilePath);

      // .env.example at project root
      for (const pf of providerFiles) {
        if (pf.relativePath.includes('.env')) {
          writeFileSync(join(projectDir, '.env.example'), pf.content, { encoding: 'utf-8', mode: FILE_MODE });
          writtenPaths.push(join(projectDir, '.env.example'));
          break;
        }
      }

      // Cloud Run service.yaml / task-definition.json at project root
      for (const pf of providerFiles) {
        if (pf.relativePath.includes('service.yaml') || pf.relativePath.includes('task-definition')) {
          const fileName = pf.relativePath.split('/').pop()!;
          writeFileSync(join(projectDir, fileName), pf.content, { encoding: 'utf-8', mode: FILE_MODE });
          writtenPaths.push(join(projectDir, fileName));
          break;
        }
      }

      // Makefile
      const makefileContent = [
        '# Generated by Phase 4 pipeline — do not edit manually',
        '.PHONY: build test dev docker deploy clean',
        '',
        'build:',
        '\tnpm run build',
        hasRustOptimizer ? '\tcd optimizer-engine && cargo build --release' : '',
        '',
        'test:',
        '\tnpm test',
        hasRustOptimizer ? '\tcd optimizer-engine && cargo test' : '',
        '',
        'dev:',
        '\tnpm run dev',
        '',
        'docker:',
        `\tdocker build -t ${serviceName} .`,
        '',
        'deploy:',
        `\tgcloud run deploy ${serviceName} --image gcr.io/$$(gcloud config get-value project)/${serviceName} --region us-central1`,
        '',
        'clean:',
        '\trm -rf dist',
        hasRustOptimizer ? '\tcd optimizer-engine && cargo clean' : '',
        '',
      ].filter(Boolean).join('\n');
      writeFileSync(join(projectDir, 'Makefile'), makefileContent, { encoding: 'utf-8', mode: FILE_MODE });
      writtenPaths.push(join(projectDir, 'Makefile'));

    } catch (err) {
      // Non-fatal — deployment files in deployment/ dir still exist
      console.error(`[deployment] ADR-063: Could not copy to project/: ${err instanceof Error ? err.message : String(err)}`);
    }

    const finalGenSpan = endSpan(genSpan, 'ok', { filesGenerated: writtenPaths.length, cloudRunService: serviceName });
    emitSpan(finalGenSpan);

    const finalRootSpan = endSpan(rootSpan, 'ok', {
      language,
      traceIdShort,
      cloudProvider,
      filesGenerated: writtenPaths.length,
      cloudRunService: serviceName,
    });
    emitSpan(finalRootSpan);

    const providerLabel: Record<CloudProvider, string> = {
      gcp: 'Cloud Run',
      aws: 'ECS/Fargate',
      azure: 'Container Apps',
      alibaba: 'Alibaba Cloud',
      'on-prem': 'on-prem',
    };

    const timing = Date.now() - startTime;
    const fileNames = deployFiles.map((f) => f.relativePath.replace('deployment/', '')).join(', ');
    const output: Phase4StageOutput = {
      stage: 'deployment-generation',
      status: 'completed',
      data: {
        files: deployFiles,
        cloudRunService: serviceName,
      } satisfies DeploymentOutput,
      artifacts: writtenPaths,
      timing,
      summary:
        `Generated deployment descriptors (${language}, ${providerLabel[cloudProvider]}): ` +
        `${fileNames} ` +
        `for service "${serviceName}" ` +
        `(${writtenPaths.length} files in ${timing}ms)`,
    };

    context.stageOutputs.set('deployment-generation', output);
    return output;
  } catch (err: unknown) {
    const errorMessage = err instanceof Error ? err.message : String(err);

    const finalRootSpan = endSpan(rootSpan, 'error', { error: errorMessage });
    emitSpan(finalRootSpan);

    const timing = Date.now() - startTime;
    const output: Phase4StageOutput = {
      stage: 'deployment-generation',
      status: 'failed',
      data: { error: errorMessage },
      artifacts: [],
      timing,
      summary: `Deployment generation failed: ${errorMessage}`,
    };

    context.stageOutputs.set('deployment-generation', output);
    return output;
  }
}

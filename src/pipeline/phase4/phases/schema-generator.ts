function toTableSlug(name: string): string {
  return name
    .replace(/Context$/i, '')
    .replace(/Aggregate$/i, '')
    .replace(/([a-z])([A-Z])/g, '$1_$2')
    .replace(/[^a-zA-Z0-9]+/g, '_')
    .replace(/^_|_$/g, '')
    .toLowerCase();
}

function toDirSlug(name: string): string {
  return toTableSlug(name);
}


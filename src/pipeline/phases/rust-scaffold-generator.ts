/**
 * Rust Cargo-workspace scaffold generator — ADR-PIPELINE-115 §D4/§D5.
 *
 * Subsumes the single-file `phase4/phases/rust-optimizer-generator.ts` (which
 * remains for the ADR-057 compute-engine use case) by emitting the *full*
 * Cargo workspace that `decideScaffoldEmission` routes a Rust-resolved run to:
 *
 *   <outDir>/
 *     Cargo.toml                 workspace manifest (members = domain crates)
 *     crates/domain/Cargo.toml   [lib] crate
 *     crates/domain/src/lib.rs   aggregate types / value objects / events
 *     crates/api/Cargo.toml      [[bin]] crate
 *     crates/api/src/main.rs     HTTP server entry point
 *     .cargo/config.toml         workspace cargo config
 *     README.md                  build instructions
 *
 * Two layers, per the ADR:
 *   - DETERMINISTIC structure (manifests, dirs, .cargo/config.toml) is emitted
 *     directly from the `{{placeholder}}` templates — no engine required.
 *   - Rust SOURCE bodies (domain types, api handlers) are filled by the engine
 *     via `generateClaudeText()` when `resolveBackend().tier !== 'none'`.
 *     When `tier === 'none'`, the loud-failure protocol (§D5) emits
 *     `LANG-FAIL-001.md` instead — never a TypeScript surrogate.
 */

import * as fs from 'node:fs';
import * as path from 'node:path';

import { renderTemplate } from '../scaffolds/template-loader.js';
import { resolveBackend, type BackendResolution } from '../backend-resolver.js';
import { generateClaudeText } from '../../runtime/claude-code-runner.js';
import { generateCodexText, isCodexError } from '../../runtime/codex-runner.js';

const DIR_MODE = 0o700;
const FILE_MODE = 0o600;

const GENERATED_MARKER =
  'Auto-generated by Agentics pipeline (ADR-PIPELINE-115) — do not edit by hand';

/** Inputs describing the resolved language decision and project identity. */
export interface RustScaffoldContext {
  /** Human/project name used in crate metadata and README. */
  projectName: string;
  /** Resolved primary language (always 'rust' on this path). */
  resolvedLanguage: string;
  /** Resolver confidence (0.0–1.0); surfaced in the README + LANG-FAIL. */
  resolvedConfidence: number;
  /** Human-readable rationale from the resolver. */
  resolvedRationale: string;
}

export interface RustScaffoldResult {
  status: 'completed' | 'failed';
  /** Reason on failure (e.g. 'no-engine-available'). */
  reason?: string;
  /** Relative paths written under outDir. */
  filesWritten: string[];
  /** Backend tier observed (when the engine path ran). */
  tier?: BackendResolution['tier'];
}

function sanitizeCrateName(name: string): string {
  const cleaned = name.replace(/[^a-z0-9_]+/gi, '-').replace(/^-+|-+$/g, '').toLowerCase();
  return cleaned.length > 0 ? cleaned : 'app';
}

function writeFile(filePath: string, content: string): void {
  fs.mkdirSync(path.dirname(filePath), { recursive: true, mode: DIR_MODE });
  fs.writeFileSync(filePath, content, { encoding: 'utf-8', mode: FILE_MODE });
}

const DEFAULT_DOMAIN_BODY = `// TODO(engine): aggregate roots, value objects, and domain events are filled
// by the synthesis engine from the phase-4 DDD model. This placeholder keeps
// the crate compiling under \`cargo check\` until then.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Aggregate {
    pub id: EntityId,
}

impl Aggregate {
    pub fn new(id: EntityId) -> Self {
        Aggregate { id }
    }
}`;

const DEFAULT_API_BODY =
  'TODO(engine): HTTP handlers are filled by the synthesis engine from the SPARC API contracts.';

/**
 * Emit the deterministic Cargo workspace skeleton from templates. Synchronous;
 * requires no engine. The source bodies are template placeholders (valid Rust)
 * which `synthesizeRustSources` later upgrades when an engine is available.
 *
 * @returns the relative paths written under `outDir`.
 */
export function emitRustWorkspaceSkeleton(
  outDir: string,
  ctx: RustScaffoldContext,
  bodies?: { domainBody?: string; apiBody?: string },
): string[] {
  const cratePrefix = sanitizeCrateName(ctx.projectName);
  const written: string[] = [];

  const emit = (rel: string, content: string): void => {
    writeFile(path.join(outDir, rel), content);
    written.push(rel);
  };

  // Workspace manifest.
  emit(
    'Cargo.toml',
    renderTemplate('rust-cargo-workspace.toml.tmpl', {
      generated_marker: GENERATED_MARKER,
      members: ['    "crates/domain",', '    "crates/api",'].join('\n'),
    }),
  );

  // Domain crate ([lib]).
  emit(
    path.join('crates', 'domain', 'Cargo.toml'),
    renderTemplate('rust-cargo-crate.toml.tmpl', {
      generated_marker: GENERATED_MARKER,
      crate_name: `${cratePrefix}-domain`,
      extra_dependencies: '',
      crate_target: '[lib]\nname = "domain"\npath = "src/lib.rs"',
    }),
  );
  emit(
    path.join('crates', 'domain', 'src', 'lib.rs'),
    renderTemplate('rust-domain-lib.rs.tmpl', {
      generated_marker: GENERATED_MARKER,
      project_name: ctx.projectName,
      domain_body: bodies?.domainBody ?? DEFAULT_DOMAIN_BODY,
    }),
  );

  // API crate ([[bin]]).
  emit(
    path.join('crates', 'api', 'Cargo.toml'),
    renderTemplate('rust-cargo-crate.toml.tmpl', {
      generated_marker: GENERATED_MARKER,
      crate_name: `${cratePrefix}-api`,
      extra_dependencies: 'domain = { path = "../domain" }',
      crate_target: `[[bin]]\nname = "${cratePrefix}-api"\npath = "src/main.rs"`,
    }),
  );
  emit(
    path.join('crates', 'api', 'src', 'main.rs'),
    renderTemplate('rust-api-main.rs.tmpl', {
      generated_marker: GENERATED_MARKER,
      project_name: ctx.projectName,
      api_body: bodies?.apiBody ?? DEFAULT_API_BODY,
    }),
  );

  // Workspace cargo config (deterministic; small enough to inline).
  emit(
    path.join('.cargo', 'config.toml'),
    `# ${GENERATED_MARKER}\n[build]\n# target-dir = "target"\n\n[profile.release]\nlto = true\nopt-level = 3\n`,
  );

  // README with build instructions + resolver provenance.
  emit(
    'README.md',
    renderTemplate('README.md.tmpl', {
      generated_marker: GENERATED_MARKER,
      project_name: ctx.projectName,
      resolved_language: ctx.resolvedLanguage,
      resolved_confidence: ctx.resolvedConfidence.toFixed(2),
      resolved_rationale: ctx.resolvedRationale,
    }),
  );

  return written;
}

/**
 * Write the ADR-PIPELINE-116 loud-failure artifact for the Rust path.
 *
 * Used for both §D5 (`no-engine-available`) and §D3 (`unsupported-language`).
 * Returns the absolute path of the artifact written.
 */
export function writeLangFailArtifact(
  runDir: string,
  reason: 'no-engine-available' | 'unsupported-language',
  ctx: { resolvedLanguage: string; resolvedConfidence?: number; resolvedRationale?: string; detail?: string },
): string {
  const dir = path.join(runDir, 'phase5b');
  const artifactPath = path.join(dir, 'LANG-FAIL-001.md');
  const message =
    reason === 'no-engine-available'
      ? 'Rust scaffold generation requires a working LLM engine (ruflo or `claude --print`). ' +
        'None was available (backend tier = none). No TypeScript scaffold was emitted as a ' +
        'substitute — a surrogate would misrepresent the requested output language ' +
        '(ADR-PIPELINE-115 §D5, ADR-PIPELINE-116).'
      : `The resolved implementation language "${ctx.resolvedLanguage}" has no scaffold path. ` +
        'Supported scaffold languages are: rust, typescript, python (ADR-PIPELINE-115 §D3).';

  const body = `# LANG-FAIL-001

**Status:** Failed
**Reason:** ${reason}
**Resolved language:** ${ctx.resolvedLanguage}${
    ctx.resolvedConfidence !== undefined ? ` (confidence ${ctx.resolvedConfidence.toFixed(2)})` : ''
  }
${ctx.resolvedRationale ? `**Rationale:** ${ctx.resolvedRationale}\n` : ''}${
    ctx.detail ? `**Detail:** ${ctx.detail}\n` : ''
  }
${message}

<!--
ADR-PIPELINE-116: this LANG-FAIL-001 artifact resolves to phase-5b engine_tier
'none', which drives the top-level run_verdict to 'degraded'/'failed' and the
CLI exit code to 1/2 (see auto-chain deriveEngineTiers / writeRunVerdictToManifest).
-->
`;
  writeFile(artifactPath, body);
  return artifactPath;
}

/**
 * Build the synthesis prompt for the domain crate body from whatever
 * SPARC/ADR/DDD artifacts exist under the run directory. Best-effort: missing
 * artifacts simply produce a leaner prompt.
 */
function buildDomainPrompt(runDir: string, ctx: RustScaffoldContext): string {
  const reads: string[] = [];
  const tryRead = (rel: string, label: string): void => {
    const p = path.join(runDir, rel);
    try {
      if (fs.statSync(p).isFile()) {
        reads.push(`## ${label}\n${fs.readFileSync(p, 'utf-8').slice(0, 8000)}`);
      }
    } catch {
      /* optional */
    }
  };
  tryRead(path.join('phase3', 'sparc', 'sparc-combined.json'), 'SPARC');
  tryRead(path.join('phase4', 'ddd', 'domain-model.json'), 'DDD domain model');

  return [
    `You are generating the Rust domain crate (\`crates/domain/src/lib.rs\`) body for "${ctx.projectName}".`,
    'Output ONLY the Rust items (structs, enums, impls) that go where the {{domain_body}} marker is.',
    'Do not emit a fenced code block, module wrapper, use-statements, or tests — those already exist.',
    'Types must derive Serialize/Deserialize and compile under `cargo check`.',
    '',
    ...reads,
  ].join('\n');
}

/**
 * Synthesize Rust source bodies via the engine and re-emit the workspace with
 * them filled in. Best-effort: on any failure the skeleton bodies are kept.
 */
export async function synthesizeRustSources(
  outDir: string,
  runDir: string,
  ctx: RustScaffoldContext,
  runId?: string,
): Promise<{ filled: boolean }> {
  try {
    const prompt = buildDomainPrompt(runDir, ctx);
    // ADR-112 §D2: ruflo/claude happy paths first; codex is the tier-3 fallback
    // reached only when the resolved backend tier is 'codex' (i.e. ruflo and
    // claude --print both unavailable). The claude path is never altered.
    // NOTE: codex transport not live-validated in this env (no codex CLI installed).
    const backend = await resolveBackend();
    let domainBody: string;
    if (backend.tier === 'codex') {
      const codexOut = await generateCodexText(prompt, {
        ...(runId ? { runId } : {}),
        label: 'rust-domain-synthesis (codex)',
      });
      if (isCodexError(codexOut)) return { filled: false };
      domainBody = codexOut.trim();
    } else {
      domainBody = (await generateClaudeText(prompt, {
        ...(runId ? { runId } : {}),
        label: 'rust-domain-synthesis',
      })).trim();
    }
    if (domainBody.length === 0) return { filled: false };
    emitRustWorkspaceSkeleton(outDir, ctx, { domainBody });
    return { filled: true };
  } catch {
    return { filled: false };
  }
}

/**
 * Full Rust scaffold orchestrator (§D4 + §D5). Resolves the synthesis backend
 * and either emits the engine-filled Cargo workspace or, when no engine is
 * available, the LANG-FAIL-001 loud-failure artifact.
 *
 * This is the engine-aware entry point intended to be invoked from the async
 * pipeline. The synchronous `decideScaffoldEmission` gate emits the
 * deterministic skeleton + handles §D5 via the persisted backend tier; this
 * function additionally fills the source bodies when an engine exists.
 */
export async function generateRustScaffold(opts: {
  runDir: string;
  outDir: string;
  ctx: RustScaffoldContext;
  runId?: string;
}): Promise<RustScaffoldResult> {
  const { runDir, outDir, ctx, runId } = opts;
  const backend = await resolveBackend();

  if (backend.tier === 'none') {
    // §D5 — loud failure; never emit a TypeScript surrogate.
    writeLangFailArtifact(runDir, 'no-engine-available', {
      resolvedLanguage: ctx.resolvedLanguage,
      resolvedConfidence: ctx.resolvedConfidence,
      resolvedRationale: ctx.resolvedRationale,
      detail: backend.reason,
    });
    return { status: 'failed', reason: 'no-engine-available', filesWritten: [], tier: backend.tier };
  }

  // Deterministic structure first, then engine-filled bodies.
  const written = emitRustWorkspaceSkeleton(outDir, ctx);
  await synthesizeRustSources(outDir, runDir, ctx, runId);
  return { status: 'completed', filesWritten: written, tier: backend.tier };
}

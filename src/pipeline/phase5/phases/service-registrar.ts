// Helper: Attempt live registration via Cloud Function
// ============================================================================

/**
 * Attempt to invoke the connector-hub/erp-surface Cloud Function for live
 * registration. This is a best-effort call: if the function is unreachable
 * (common in local/CI environments), the caller falls back to deterministic
 * artifact generation.
 *
 * @returns The Cloud Function response, or null if unreachable.
 */
async function attemptLiveRegistration(
  _registration: ERPSurfaceRegistration,
): Promise<Record<string, unknown> | null> {
  try {
    // The Cloud Function URL follows the connector-hub naming convention:
    // https://<region>-<project>.cloudfunctions.net/erp-surface-register
    // In CI/local mode, this will not be reachable.
    // We attempt a quick connectivity check with a short timeout.

    // NOTE: Actual HTTP invocation is intentionally omitted in the deterministic
    // pipeline. Live registration requires runtime credentials and network
    // access that are only available in deployed environments. This function
    // serves as the extension point for live-mode registration.

    return null;
  } catch {
    // Cloud Function unreachable — fall back to local artifact generation
    return null;
  }
}

// ============================================================================
// Helper: Load erp-surface repo definitions if cached
// ============================================================================

/**
 * If the erp-surface platform repo is cached locally, read its procurement
 * surface definition for enrichment. Returns null if not cached.
 */
function loadERPSurfaceDefinitions(
  platformRepoPaths: Record<string, string>,
): Record<string, unknown> | null {
  const erpSurfacePath = platformRepoPaths['erp-surface'];
  if (!erpSurfacePath) return null;

  const definitionsPath = join(erpSurfacePath, 'surfaces', 'procurement', 'definition.json');
  if (!existsSync(definitionsPath)) return null;

  try {
    const raw = readFileSync(definitionsPath, 'utf-8');
    return JSON.parse(raw) as Record<string, unknown>;
  } catch {
    // Malformed or unreadable — skip enrichment
    return null;
  }
}

// ============================================================================
// Helper: Write a JSON artifact to disk
// ============================================================================

/**
 * Write a JSON artifact to disk with proper formatting and permissions.
 */
function writeJsonArtifact(absPath: string, data: unknown): void {
  const dir = absPath.substring(0, absPath.lastIndexOf('/'));
  mkdirSync(dir, { recursive: true, mode: DIR_MODE });
  const content = JSON.stringify(data, null, 2) + '\n';
  writeFileSync(absPath, content, { encoding: 'utf-8', mode: FILE_MODE });
}

// ============================================================================
// Main: registerERPSurface
// ============================================================================

/**
 * Stage 2: Register the service on the ERP surface.
 *
 * Builds a complete ERPSurfaceRegistration including endpoint mappings for
 * the four procurement use cases, operational endpoints, VPC configuration,
 * IAM roles, and governance controls. Writes registration.json and
 * erp-surface-mapping.json to the Phase 5 output directory.
 *
 * If the erp-surface platform repo is cached, reads procurement surface
 * definitions for enrichment. Attempts live Cloud Function registration
 * with graceful fallback to deterministic local generation.
 *
 * @param context - The mutable Phase 5 pipeline context
 * @returns Stage output describing success or failure
 */
export function registerERPSurface(context: Phase5Context): Phase5StageOutput {
  const startTime = Date.now();
  const rootSpan = createSpan('service-registration', 'register-erp-surface', {
    phase5Dir: context.phase5Dir,
    erpSystem: context.phase4Artifacts.erpSystem,
  });

  try {
    // -------------------------------------------------------------------------
    // Step 1: Extract ERP system info from context
    // -------------------------------------------------------------------------
    const { erpSystem, apiOnly } = context.phase4Artifacts;
    const erpVendor = resolveERPVendor(erpSystem);
    const serviceName = deriveServiceName(context.scenarioQuery);

    const infoSpan = createSpan(
      'service-registration',
      'extract-erp-info',
      { erpSystem, erpVendor, serviceName, apiOnly },
      rootSpan.spanId,
    );
    const finalInfoSpan = endSpan(infoSpan, 'ok', { erpSystem, erpVendor, serviceName });
    emitSpan(finalInfoSpan);
    context.telemetrySpans.push(finalInfoSpan);

    // -------------------------------------------------------------------------
    // Step 2: Check for cached erp-surface repo definitions
    // -------------------------------------------------------------------------
    const repoSpan = createSpan(
      'service-registration',
      'load-erp-surface-definitions',
      {},
      rootSpan.spanId,
    );

    const surfaceDefinitions = loadERPSurfaceDefinitions(context.platformRepoPaths);

    const finalRepoSpan = endSpan(repoSpan, 'ok', {
      hasSurfaceDefinitions: surfaceDefinitions !== null,
    });
    emitSpan(finalRepoSpan);
    context.telemetrySpans.push(finalRepoSpan);

    // -------------------------------------------------------------------------
    // Step 3: Build the ERPSurfaceRegistration
    // -------------------------------------------------------------------------
    const buildSpan = createSpan(
      'service-registration',
      'build-registration',
      { serviceName, erpVendor },
      rootSpan.spanId,
    );

    const endpoints = buildProcurementEndpoints();

    const registration: ERPSurfaceRegistration = {
      registration_id: randomUUID(),
      service_name: serviceName,
      erp_system: erpSystem,
      erp_vendor: erpVendor,
      surface_domain: 'procurement',
      endpoints,
      connector_type: 'odata-v4',
      vpc_config: {
        connector_name: 'sap-connector',
        cidr_range: '10.8.0.0/28',
        ingress: 'internal-only',
      },
      iam_config: {
        service_account: `${serviceName}-sa@PROJECT_ID.iam.gserviceaccount.com`,
        roles: [
          'roles/run.invoker',
          'roles/secretmanager.secretAccessor',
          'roles/cloudsql.client',
          'roles/logging.logWriter',
          'roles/monitoring.metricWriter',
        ],
      },
      governance: {
        read_only: true,
        audit_enabled: true,
        pii_redaction: true,
        max_tokens_per_request: 4096,
      },
      created_at: new Date().toISOString(),
    };

    const finalBuildSpan = endSpan(buildSpan, 'ok', {
      registrationId: registration.registration_id,
      endpointCount: endpoints.length,
      connectorType: registration.connector_type,
    });
    emitSpan(finalBuildSpan);
    context.telemetrySpans.push(finalBuildSpan);

    // -------------------------------------------------------------------------
    // Step 4: Attempt live Cloud Function registration
    // -------------------------------------------------------------------------
    const liveSpan = createSpan(
      'service-registration',
      'attempt-live-registration',
      {},
      rootSpan.spanId,
    );

    // Fire-and-forget: live registration is best-effort.
    // We do not await the promise in the synchronous pipeline; the local
    // artifacts are always the source of truth.
    void attemptLiveRegistration(registration);

    const finalLiveSpan = endSpan(liveSpan, 'ok', { mode: 'local-deterministic' });
    emitSpan(finalLiveSpan);
    context.telemetrySpans.push(finalLiveSpan);

    // -------------------------------------------------------------------------
    // Step 5: Write registration.json
    // -------------------------------------------------------------------------
    const writeSpan = createSpan(
      'service-registration',
      'write-registration-artifacts',
      { phase5Dir: context.phase5Dir },
      rootSpan.spanId,
    );

    mkdirSync(context.phase5Dir, { recursive: true, mode: DIR_MODE });

    const writtenPaths: string[] = [];

    const registrationPath = join(context.phase5Dir, 'registration.json');
    writeJsonArtifact(registrationPath, {
      _generated: GENERATED_HEADER,
      ...registration,
    });
    writtenPaths.push(registrationPath);

    // -------------------------------------------------------------------------
    // Step 6: Write erp-surface-mapping.json (connector-hub format)
    // -------------------------------------------------------------------------
    const connectorMapping = buildConnectorHubMapping(registration);
    const mappingPath = join(context.phase5Dir, 'erp-surface-mapping.json');
    writeJsonArtifact(mappingPath, connectorMapping);
    writtenPaths.push(mappingPath);

    const finalWriteSpan = endSpan(writeSpan, 'ok', { filesWritten: writtenPaths.length });
    emitSpan(finalWriteSpan);
    context.telemetrySpans.push(finalWriteSpan);

    // -------------------------------------------------------------------------
    // Step 7: Build and return stage output
    // -------------------------------------------------------------------------
    const finalRootSpan = endSpan(rootSpan, 'ok', {
      registrationId: registration.registration_id,
      serviceName,
      erpSystem,
      erpVendor,
      endpointCount: endpoints.length,
      filesWritten: writtenPaths.length,
      hasSurfaceDefinitions: surfaceDefinitions !== null,
    });
    emitSpan(finalRootSpan);
    context.telemetrySpans.push(finalRootSpan);

    const timing = Date.now() - startTime;

    const output: Phase5StageOutput = {
      stage: 'service-registration',
      status: 'completed',
      data: {
        registration,
        connectorMapping,
        surfaceDefinitions,
      },
      artifacts: writtenPaths,
      timing,
    };

    context.stageOutputs.set('service-registration', output);
    return output;
  } catch (err: unknown) {
    const errorMessage = err instanceof Error ? err.message : String(err);

    const finalRootSpan = endSpan(rootSpan, 'error', { error: errorMessage });
    emitSpan(finalRootSpan);
    context.telemetrySpans.push(finalRootSpan);

    const timing = Date.now() - startTime;

    const output: Phase5StageOutput = {
      stage: 'service-registration',
      status: 'failed',
      data: { error: errorMessage },
      artifacts: [],
      timing,
    };

    context.stageOutputs.set('service-registration', output);
    return output;
  }
}

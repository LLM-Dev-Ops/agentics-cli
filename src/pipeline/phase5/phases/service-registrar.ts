/**
 * Phase 5 — Stage 2: ERP Surface Service Registration
 *
 * Generates registration.json and erp-surface-mapping.json.
 * Uses the erp-surface repo's registration schema and the
 * agentics-contracts ERPDeploymentArtifact for normalization.
 *
 * If the connector-hub/erp-surface Cloud Function is reachable,
 * calls it for live registration. Otherwise generates deterministic
 * registration artifacts.
 */

import { writeFileSync, mkdirSync, existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import type { Phase5Context, Phase5StageOutput, ERPSurfaceRegistration, ERPEndpointMapping } from '../types.js';
import { createSpan, endSpan, emitSpan } from '../../phase2/telemetry.js';

// ============================================================================
// Constants
// ============================================================================

const DIR_MODE = 0o700;
const FILE_MODE = 0o600;

/** Header written at the top of every generated JSON artifact. */
const GENERATED_HEADER = 'Generated by Phase 5 pipeline — do not edit manually';

// ============================================================================
// Helper: Derive service name from scenario query
// ============================================================================

/**
 * Derive a kebab-case service name from the scenario query string.
 * Extracts key terms and normalizes to a DNS-safe identifier.
 *
 * @example "SAP procurement copilot" -> "sap-procurement-copilot"
 */
function deriveServiceName(scenarioQuery: string): string {
  return scenarioQuery
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 63) || 'erp-service';
}

// ============================================================================
// Helper: Resolve ERP vendor from system identifier
// ============================================================================

/**
 * Map an ERP system string to the canonical vendor identifier.
 */
function resolveERPVendor(
  erpSystem: string,
): ERPSurfaceRegistration['erp_vendor'] {
  const normalized = erpSystem.toLowerCase();
  if (normalized.includes('sap')) return 'sap';
  if (normalized.includes('oracle')) return 'oracle';
  if (normalized.includes('dynamics')) return 'dynamics';
  if (normalized.includes('workday')) return 'workday';
  if (normalized.includes('netsuite')) return 'netsuite';
  if (normalized.includes('servicenow')) return 'servicenow';
  return 'sap'; // default for procurement scenarios
}


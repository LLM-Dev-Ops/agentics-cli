/**
 * Generate deploy.sh: the primary deployment script for Cloud Run.
 *
 * Builds the container image, pushes it to GCR, and deploys to Cloud Run
 * with all production settings: VPC connector, Secret Manager references,
 * least-privilege service account, and internal-only ingress.
 */
function generateDeployScript(vars: DeploymentVars, erpSystem: string): string {
  return [
    SCRIPT_HEADER,
    '# ============================================================================',
    `# Deploy ${vars.serviceName} to Cloud Run`,
    '# ============================================================================',
    '',
    '# Configuration (override via environment variables)',
    'GCP_PROJECT_ID=${GCP_PROJECT_ID:?ERROR: GCP_PROJECT_ID must be set}',
    `GCP_REGION="\${GCP_REGION:-${vars.region}}"`,
    `SERVICE_NAME="\${SERVICE_NAME:-${vars.serviceName}}"`,
    'IMAGE_TAG="${IMAGE_TAG:-latest}"',
    'IMAGE_URL="gcr.io/${GCP_PROJECT_ID}/${SERVICE_NAME}:${IMAGE_TAG}"',
    `SERVICE_ACCOUNT="\${SERVICE_ACCOUNT:-${vars.serviceAccount}}"`,
    `VPC_CONNECTOR="\${VPC_CONNECTOR:-${vars.vpcConnector}}"`,
    '',
    'echo "=================================================================="',
    'echo "Deploying ${SERVICE_NAME} to Cloud Run"',
    'echo "  Project:         ${GCP_PROJECT_ID}"',
    'echo "  Region:          ${GCP_REGION}"',
    'echo "  Image:           ${IMAGE_URL}"',
    'echo "  Service Account: ${SERVICE_ACCOUNT}"',
    'echo "  VPC Connector:   ${VPC_CONNECTOR}"',
    'echo "=================================================================="',
    '',
    '# Step 1: Authenticate with GCP (if not already authenticated)',
    'echo "[1/5] Checking GCP authentication..."',
    'gcloud auth print-identity-token > /dev/null 2>&1 || {',
    '  echo "Not authenticated. Run: gcloud auth login"',
    '  exit 1',
    '}',
    '',
    '# Step 2: Set the active project',
    'echo "[2/5] Setting project to ${GCP_PROJECT_ID}..."',
    'gcloud config set project "${GCP_PROJECT_ID}"',
    '',
    '# Step 3: Build the container image',
    'echo "[3/5] Building container image..."',
    'gcloud builds submit \\',
    '  --tag "${IMAGE_URL}" \\',
    '  --timeout=600s \\',
    '  .',
    '',
    '# Step 4: Deploy to Cloud Run',
    'echo "[4/5] Deploying to Cloud Run..."',
    'gcloud run deploy "${SERVICE_NAME}" \\',
    '  --image "${IMAGE_URL}" \\',
    '  --region "${GCP_REGION}" \\',
    '  --platform managed \\',
    '  --no-allow-unauthenticated \\',
    '  --vpc-connector "${VPC_CONNECTOR}" \\',
    '  --vpc-egress all-traffic \\',
    '  --service-account "${SERVICE_ACCOUNT}" \\',
    '  --set-secrets "SAP_API_KEY=sap-api-key:latest,SAP_CLIENT_CERT=sap-client-cert:latest,SAP_OAUTH_SECRET=sap-oauth-secret:latest" \\',
    `  --set-env-vars "NODE_ENV=production,PORT=8080,ERP_SYSTEM=${erpSystem},LOG_LEVEL=info" \\`,
    '  --min-instances 0 \\',
    '  --max-instances 10 \\',
    '  --memory 512Mi \\',
    '  --cpu 1 \\',
    '  --timeout 300 \\',
    '  --concurrency 80 \\',
    '  --ingress internal-and-cloud-load-balancing \\',
    '  --cpu-throttling \\',
    '  --quiet',
    '',
    '# Step 5: Verify deployment',
    'echo "[5/5] Verifying deployment..."',
    'SERVICE_URL=$(gcloud run services describe "${SERVICE_NAME}" \\',
    '  --region "${GCP_REGION}" \\',
    '  --format "value(status.url)")',
    '',
    'echo ""',
    'echo "=================================================================="',
    'echo "Deployment complete!"',
    'echo "  Service URL: ${SERVICE_URL}"',
    'echo "  Health:      ${SERVICE_URL}/api/v1/health"',
    'echo "=================================================================="',
    '',
  ].join('\n');
}

/**
 * Generate teardown.sh: cleanup script that removes all deployed resources.
 *
 * Deletes the Cloud Run service, container images, IAM bindings, and
 * optionally the service account.
 */
function generateTeardownScript(vars: DeploymentVars): string {
  return [
    SCRIPT_HEADER,
    '# ============================================================================',
    `# Teardown ${vars.serviceName} — remove all deployed resources`,
    '# ============================================================================',
    '',
    'GCP_PROJECT_ID=${GCP_PROJECT_ID:?ERROR: GCP_PROJECT_ID must be set}',
    `GCP_REGION="\${GCP_REGION:-${vars.region}}"`,
    `SERVICE_NAME="\${SERVICE_NAME:-${vars.serviceName}}"`,
    `SERVICE_ACCOUNT="\${SERVICE_ACCOUNT:-${vars.serviceAccount}}"`,
    '',
    'echo "=================================================================="',
    'echo "WARNING: Tearing down ${SERVICE_NAME}"',
    'echo "  This will DELETE the Cloud Run service and associated resources."',
    'echo "=================================================================="',
    'echo ""',
    'read -rp "Are you sure? (y/N): " CONFIRM',
    'if [[ "${CONFIRM}" != "y" && "${CONFIRM}" != "Y" ]]; then',
    '  echo "Teardown cancelled."',
    '  exit 0',
    'fi',
    '',
    '# Step 1: Delete Cloud Run service',
    'echo "[1/4] Deleting Cloud Run service..."',
    'gcloud run services delete "${SERVICE_NAME}" \\',
    '  --region "${GCP_REGION}" \\',
    '  --quiet 2>/dev/null || echo "  Service not found — skipping."',
    '',
    '# Step 2: Delete container images from GCR',
    'echo "[2/4] Cleaning up container images..."',
    'gcloud container images list-tags "gcr.io/${GCP_PROJECT_ID}/${SERVICE_NAME}" \\',
    '  --format="get(digest)" 2>/dev/null | while read -r DIGEST; do',
    '  gcloud container images delete \\',
    '    "gcr.io/${GCP_PROJECT_ID}/${SERVICE_NAME}@${DIGEST}" \\',
    '    --quiet --force-delete-tags 2>/dev/null || true',
    'done',
    'echo "  Container images cleaned."',
    '',
    '# Step 3: Remove IAM policy bindings for the service account',
    'echo "[3/4] Removing IAM bindings for ${SERVICE_ACCOUNT}..."',
    'for ROLE in roles/run.invoker roles/secretmanager.secretAccessor roles/cloudsql.client roles/logging.logWriter roles/monitoring.metricWriter; do',
    '  gcloud projects remove-iam-policy-binding "${GCP_PROJECT_ID}" \\',
    '    --member "serviceAccount:${SERVICE_ACCOUNT}" \\',
    '    --role "${ROLE}" \\',
    '    --quiet 2>/dev/null || true',
    'done',
    'echo "  IAM bindings removed."',
    '',
    '# Step 4: Optionally delete the service account',
    'echo "[4/4] Optionally deleting service account..."',
    'read -rp "Delete service account ${SERVICE_ACCOUNT}? (y/N): " DEL_SA',
    'if [[ "${DEL_SA}" == "y" || "${DEL_SA}" == "Y" ]]; then',
    '  gcloud iam service-accounts delete "${SERVICE_ACCOUNT}" \\',
    '    --quiet 2>/dev/null || echo "  Service account not found."',
    'fi',
    '',
    'echo ""',
    'echo "=================================================================="',
    'echo "Teardown complete."',
    'echo "=================================================================="',
    '',
  ].join('\n');
}


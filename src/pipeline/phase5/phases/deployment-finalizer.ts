/**
 * Stage 4: Generate production-ready deployment scripts.
 *
 * Creates the `phase5/deploy/` directory and generates five deployment
 * artifacts:
 *
 * 1. **deploy.sh** - Primary gcloud CLI deployment script with VPC connector,
 *    Secret Manager references, least-privilege service account, and
 *    internal-only ingress.
 *
 * 2. **teardown.sh** - Reverse of deploy.sh: deletes Cloud Run service,
 *    container images, and IAM bindings.
 *
 * 3. **env.template** - Environment variable template with Secret Manager
 *    reference format for all production secrets.
 *
 * 4. **vpc-setup.sh** - Creates the Serverless VPC Access connector for
 *    ERP network connectivity. References infra repo patterns if cached.
 *
 * 5. **monitoring.yaml** - Cloud Monitoring alert policies for error rate,
 *    latency, instance count, and SAP connectivity.
 *
 * @param context - The mutable Phase 5 pipeline context
 * @returns Stage output describing success or failure
 */
export function finalizeDeployment(context: Phase5Context): Phase5StageOutput {
  const startTime = Date.now();
  const rootSpan = createSpan('deployment-finalization', 'finalize-deployment', {
    phase5Dir: context.phase5Dir,
    erpSystem: context.phase4Artifacts.erpSystem,
  });

  try {
    // -------------------------------------------------------------------------
    // Step 1: Derive deployment variables
    // -------------------------------------------------------------------------
    const varsSpan = createSpan(
      'deployment-finalization',
      'derive-deployment-vars',
      {},
      rootSpan.spanId,
    );

    const vars = deriveDeploymentVars(context);
    const erpSystem = context.phase4Artifacts.erpSystem;
    const infraRepoPath = resolveInfraRepoPath(context.platformRepoPaths);

    const finalVarsSpan = endSpan(varsSpan, 'ok', {
      serviceName: vars.serviceName,
      region: vars.region,
      vpcConnector: vars.vpcConnector,
      hasInfraRepo: infraRepoPath !== undefined,
    });
    emitSpan(finalVarsSpan);
    context.telemetrySpans.push(finalVarsSpan);

    // -------------------------------------------------------------------------
    // Step 2: Create the deploy/ directory
    // -------------------------------------------------------------------------
    const deployDir = join(context.phase5Dir, 'deploy');
    mkdirSync(deployDir, { recursive: true, mode: DIR_MODE });

    const writtenPaths: string[] = [];

    // -------------------------------------------------------------------------
    // Step 3: Generate all deployment scripts
    // -------------------------------------------------------------------------
    const genSpan = createSpan(
      'deployment-finalization',
      'generate-scripts',
      { deployDir },
      rootSpan.spanId,
    );

    // deploy.sh
    const deployShPath = join(deployDir, 'deploy.sh');
    writeScript(deployShPath, generateDeployScript(vars, erpSystem));
    writtenPaths.push(deployShPath);

    // teardown.sh
    const teardownShPath = join(deployDir, 'teardown.sh');
    writeScript(teardownShPath, generateTeardownScript(vars));
    writtenPaths.push(teardownShPath);

    // env.template
    const envTemplatePath = join(deployDir, 'env.template');
    writeArtifact(envTemplatePath, generateEnvTemplate(vars, erpSystem));
    writtenPaths.push(envTemplatePath);

    // vpc-setup.sh
    const vpcSetupPath = join(deployDir, 'vpc-setup.sh');
    writeScript(vpcSetupPath, generateVpcSetupScript(vars, infraRepoPath));
    writtenPaths.push(vpcSetupPath);

    // monitoring.yaml
    const monitoringPath = join(deployDir, 'monitoring.yaml');
    writeArtifact(monitoringPath, generateMonitoringYaml(vars));
    writtenPaths.push(monitoringPath);

    const finalGenSpan = endSpan(genSpan, 'ok', {
      filesGenerated: writtenPaths.length,
    });
    emitSpan(finalGenSpan);
    context.telemetrySpans.push(finalGenSpan);

    // -------------------------------------------------------------------------
    // Step 4: Build and return stage output
    // -------------------------------------------------------------------------
    const finalRootSpan = endSpan(rootSpan, 'ok', {
      serviceName: vars.serviceName,
      erpSystem,
      filesGenerated: writtenPaths.length,
      hasInfraRepo: infraRepoPath !== undefined,
    });
    emitSpan(finalRootSpan);
    context.telemetrySpans.push(finalRootSpan);

    const timing = Date.now() - startTime;

    const output: Phase5StageOutput = {
      stage: 'deployment-finalization',
      status: 'completed',
      data: {
        deployDir,
        serviceName: vars.serviceName,
        region: vars.region,
        vpcConnector: vars.vpcConnector,
        filesGenerated: writtenPaths.length,
      },
      artifacts: writtenPaths,
      timing,
    };

    context.stageOutputs.set('deployment-finalization', output);
    return output;
  } catch (err: unknown) {
    const errorMessage = err instanceof Error ? err.message : String(err);

    const finalRootSpan = endSpan(rootSpan, 'error', { error: errorMessage });
    emitSpan(finalRootSpan);
    context.telemetrySpans.push(finalRootSpan);

    const timing = Date.now() - startTime;

    const output: Phase5StageOutput = {
      stage: 'deployment-finalization',
      status: 'failed',
      data: { error: errorMessage },
      artifacts: [],
      timing,
    };

    context.stageOutputs.set('deployment-finalization', output);
    return output;
  }
}

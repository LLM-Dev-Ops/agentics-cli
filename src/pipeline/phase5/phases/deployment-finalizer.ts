// ============================================================================
// Helper: Write a script file with executable permissions
// ============================================================================

/**
 * Write a script file to disk, creating parent directories as needed.
 * Scripts get 0o700 permissions (owner read/write/execute).
 */
function writeScript(absPath: string, content: string): void {
  writeFileSync(absPath, content, { encoding: 'utf-8', mode: EXEC_MODE });
}

/**
 * Write a non-executable artifact file to disk.
 */
function writeArtifact(absPath: string, content: string): void {
  writeFileSync(absPath, content, { encoding: 'utf-8', mode: FILE_MODE });
}

// ============================================================================
// Helper: Check for infra repo patterns
// ============================================================================

/**
 * If the infra platform repo is cached, return its path.
 * Used by vpc-setup.sh for reference documentation.
 */
function resolveInfraRepoPath(
  platformRepoPaths: Record<string, string>,
): string | undefined {
  const infraPath = platformRepoPaths['infra'];
  if (!infraPath) return undefined;
  if (!existsSync(infraPath)) return undefined;
  return infraPath;
}


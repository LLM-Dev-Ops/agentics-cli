/**
 * Generate vpc-setup.sh: creates the Serverless VPC Access connector
 * required for Cloud Run to reach the ERP network.
 *
 * If the infra repo is cached, references its networking patterns.
 */
function generateVpcSetupScript(
  vars: DeploymentVars,
  infraRepoPath: string | undefined,
): string {
  let infraNote = '';
  if (infraRepoPath) {
    infraNote = [
      '# NOTE: This script follows the networking patterns from the infra repo.',
      `# Reference: ${infraRepoPath}/modules/networking/`,
      '#',
      '',
    ].join('\n');
  }

  return [
    SCRIPT_HEADER,
    '# ============================================================================',
    `# VPC Connector Setup for ${vars.serviceName}`,
    '# ============================================================================',
    '#',
    '# Creates a Serverless VPC Access connector so Cloud Run can reach',
    '# the ERP system over a private network path.',
    '#',
    infraNote,
    'GCP_PROJECT_ID=${GCP_PROJECT_ID:?ERROR: GCP_PROJECT_ID must be set}',
    `GCP_REGION="\${GCP_REGION:-${vars.region}}"`,
    `VPC_CONNECTOR="\${VPC_CONNECTOR:-${vars.vpcConnector}}"`,
    'VPC_NETWORK="${VPC_NETWORK:-default}"',
    'VPC_CIDR="${VPC_CIDR:-10.8.0.0/28}"',
    '',
    'echo "=================================================================="',
    'echo "Setting up VPC connector: ${VPC_CONNECTOR}"',
    'echo "  Project:  ${GCP_PROJECT_ID}"',
    'echo "  Region:   ${GCP_REGION}"',
    'echo "  Network:  ${VPC_NETWORK}"',
    'echo "  CIDR:     ${VPC_CIDR}"',
    'echo "=================================================================="',
    '',
    '# Step 1: Enable required APIs',
    'echo "[1/4] Enabling required APIs..."',
    'gcloud services enable vpcaccess.googleapis.com \\',
    '  --project "${GCP_PROJECT_ID}" \\',
    '  --quiet',
    '',
    '# Step 2: Create the VPC connector',
    'echo "[2/4] Creating VPC connector..."',
    'gcloud compute networks vpc-access connectors create "${VPC_CONNECTOR}" \\',
    '  --region "${GCP_REGION}" \\',
    '  --network "${VPC_NETWORK}" \\',
    '  --range "${VPC_CIDR}" \\',
    '  --min-instances 2 \\',
    '  --max-instances 10 \\',
    '  --machine-type e2-micro \\',
    '  --quiet 2>/dev/null || {',
    '    echo "  VPC connector already exists or creation failed."',
    '    echo "  Checking existing connector..."',
    '    gcloud compute networks vpc-access connectors describe "${VPC_CONNECTOR}" \\',
    '      --region "${GCP_REGION}" \\',
    '      --format "table(name, state, network, ipCidrRange)"',
    '  }',
    '',
    '# Step 3: Create firewall rules for ERP traffic',
    'echo "[3/4] Creating firewall rules..."',
    'gcloud compute firewall-rules create "allow-${VPC_CONNECTOR}-to-erp" \\',
    '  --network "${VPC_NETWORK}" \\',
    '  --allow tcp:443,tcp:8443 \\',
    '  --source-ranges "${VPC_CIDR}" \\',
    '  --target-tags "erp-backend" \\',
    '  --description "Allow VPC connector traffic to ERP system (HTTPS/OData)" \\',
    '  --quiet 2>/dev/null || echo "  Firewall rule already exists."',
    '',
    '# Step 4: Verify connectivity',
    'echo "[4/4] Verifying VPC connector status..."',
    'gcloud compute networks vpc-access connectors describe "${VPC_CONNECTOR}" \\',
    '  --region "${GCP_REGION}" \\',
    '  --format "table(name, state, network, ipCidrRange, minInstances, maxInstances)"',
    '',
    'echo ""',
    'echo "=================================================================="',
    'echo "VPC connector setup complete."',
    'echo "  Connector: ${VPC_CONNECTOR}"',
    'echo "  Use --vpc-connector=${VPC_CONNECTOR} in deploy.sh"',
    'echo "=================================================================="',
    '',
  ].join('\n');
}


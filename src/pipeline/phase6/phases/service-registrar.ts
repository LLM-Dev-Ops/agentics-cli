/**
 * Build the erp-surface-mapping.json in the connector-hub normalized format.
 */
function buildConnectorHubMapping(
  registration: ERPSurfaceRegistration,
): Record<string, unknown> {
  return {
    _generated: GENERATED_HEADER,
    schema_version: '1.0.0',
    connector_type: registration.connector_type,
    service_name: registration.service_name,
    erp_system: registration.erp_system,
    erp_vendor: registration.erp_vendor,
    routes: registration.endpoints
      .filter((ep) => ep.erp_service !== 'N/A')
      .map((ep) => ({
        method: ep.method,
        path: ep.path,
        target: {
          service: ep.erp_service,
          entity: ep.erp_entity,
          protocol: registration.connector_type,
        },
        description: ep.description,
      })),
    vpc_connector: registration.vpc_config.connector_name,
    service_account: registration.iam_config.service_account,
    auth_scheme: registration.auth_scheme ?? 'api-key',
    governance: {
      read_only: registration.governance.read_only,
      audit_enabled: registration.governance.audit_enabled,
      pii_redaction: registration.governance.pii_redaction,
      max_tokens_per_request: registration.governance.max_tokens_per_request,
    },
  };
}

// ============================================================================
// Helper: Attempt live registration via Cloud Function
// ============================================================================

async function attemptLiveRegistration(
  registration: ERPSurfaceRegistration,
): Promise<{ live: boolean; response?: Record<string, unknown>; error?: string }> {
  try {
    const config = loadEndpointConfig('connector-hub-agents');
    const { ConnectorHubAdapter } = await import('../../../adapters/base-adapter.js');
    const adapter = new ConnectorHubAdapter(config, registration.registration_id);

    const response = await adapter.invoke_agent('erp-surface', {
      action: 'register',
      registration_id: registration.registration_id,
      service_name: registration.service_name,
      erp_system: registration.erp_system,
      connector_type: registration.connector_type,
      surface_domain: registration.surface_domain,
      endpoints: registration.endpoints,
      governance: registration.governance,
      vpc_config: registration.vpc_config,
      iam_config: registration.iam_config,
    });

    if (response.status >= 200 && response.status < 300) {
      console.error(`  [ERP] Live registration succeeded (${response.status}) — ${registration.service_name} → ${registration.erp_system}`);
      return { live: true, response: response.body as Record<string, unknown> };
    }

    // Server returned an error — log but don't fail
    const bodyPreview = JSON.stringify(response.body).slice(0, 200);
    console.error(`  [ERP] Live registration returned ${response.status}: ${bodyPreview}`);
    return { live: false, error: `HTTP ${response.status}` };
  } catch (err: unknown) {
    const errMsg = err instanceof Error ? err.message : String(err);
    console.error(`  [ERP] Live registration failed: ${errMsg.slice(0, 200)}`);
    console.error(`  [ERP] Registration artifacts written locally — push manually or re-run when service is available`);
    return { live: false, error: errMsg };
  }
}

// ============================================================================
// Helper: Load erp-surface repo definitions if cached
// ============================================================================

function loadERPSurfaceDefinitions(
  platformRepoPaths: Record<string, string>,
): Record<string, unknown> | null {
  const erpSurfacePath = platformRepoPaths['erp-surface'];
  if (!erpSurfacePath) return null;

  const definitionsPath = join(erpSurfacePath, 'surfaces', 'procurement', 'definition.json');
  if (!existsSync(definitionsPath)) return null;

  try {
    const raw = readFileSync(definitionsPath, 'utf-8');
    return JSON.parse(raw) as Record<string, unknown>;
  } catch {
    return null;
  }
}

// ============================================================================
// Helper: Write a JSON artifact to disk
// ============================================================================

function writeJsonArtifact(absPath: string, data: unknown): void {
  const dir = absPath.substring(0, absPath.lastIndexOf('/'));
  mkdirSync(dir, { recursive: true, mode: DIR_MODE });
  const content = JSON.stringify(data, null, 2) + '\n';
  writeFileSync(absPath, content, { encoding: 'utf-8', mode: FILE_MODE });
}


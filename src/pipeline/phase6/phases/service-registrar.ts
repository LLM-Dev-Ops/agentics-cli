/**
 * Stage 2: Register the service on the ERP surface.
 *
 * @param context - The mutable Phase 6 pipeline context
 * @returns Stage output describing success or failure
 */
export async function registerERPSurface(context: Phase6Context): Promise<Phase6StageOutput> {
  const startTime = Date.now();
  const rootSpan = createSpan('service-registration', 'register-erp-surface', {
    phase6Dir: context.phase6Dir,
    erpSystem: context.phase5Artifacts.erpSystem,
  });

  try {
    const { erpSystem, apiOnly } = context.phase5Artifacts;
    const erpVendor = resolveERPVendor(erpSystem);
    // Derive service name from SPARC/DDD/scenario artifacts (not raw prompt text)
    const runDir = path.dirname(context.phase6Dir);
    const serviceName = deriveServiceName(context.scenarioQuery, runDir);

    const infoSpan = createSpan(
      'service-registration',
      'extract-erp-info',
      { erpSystem, erpVendor, serviceName, apiOnly },
      rootSpan.spanId,
    );
    const finalInfoSpan = endSpan(infoSpan, 'ok', { erpSystem, erpVendor, serviceName });
    emitSpan(finalInfoSpan);
    context.telemetrySpans.push(finalInfoSpan);

    const repoSpan = createSpan(
      'service-registration',
      'load-erp-surface-definitions',
      {},
      rootSpan.spanId,
    );

    const surfaceDefinitions = loadERPSurfaceDefinitions(context.platformRepoPaths);

    const finalRepoSpan = endSpan(repoSpan, 'ok', {
      hasSurfaceDefinitions: surfaceDefinitions !== null,
    });
    emitSpan(finalRepoSpan);
    context.telemetrySpans.push(finalRepoSpan);

    const buildSpan = createSpan(
      'service-registration',
      'build-registration',
      { serviceName, erpVendor },
      rootSpan.spanId,
    );

    const vendorConfig = ERP_VENDOR_CONFIG[erpVendor] ?? ERP_VENDOR_CONFIG['sap']!;
    const authConfig = resolveERPAuth(erpVendor);
    const endpoints = buildEndpointsFromDomainModel(erpVendor, context.phase6Dir);

    // Derive surface domain from scenario query keywords
    const queryLower = context.scenarioQuery.toLowerCase();
    let surfaceDomain: 'procurement' | 'finance' | 'hcm' | 'supply-chain' = 'procurement';
    if (/\b(finance|financial|accounting|ledger|invoice|billing|payment)\b/.test(queryLower)) {
      surfaceDomain = 'finance';
    } else if (/\b(hr|human\s*resource|hcm|payroll|workforce|talent|employee)\b/.test(queryLower)) {
      surfaceDomain = 'hcm';
    } else if (/\b(supply\s*chain|logistics|warehouse|inventory|shipping|fulfillment)\b/.test(queryLower)) {
      surfaceDomain = 'supply-chain';
    }

    const registration: ERPSurfaceRegistration = {
      registration_id: randomUUID(),
      service_name: serviceName,
      erp_system: erpSystem,
      erp_vendor: erpVendor,
      surface_domain: surfaceDomain,
      endpoints,
      connector_type: vendorConfig.protocol,
      auth_scheme: authConfig.scheme,
      vpc_config: {
        connector_name: vendorConfig.connectorName,
        cidr_range: '10.8.0.0/28',
        ingress: 'internal-only',
      },
      iam_config: {
        service_account: `${serviceName}-sa@PROJECT_ID.iam.gserviceaccount.com`,
        roles: [
          'roles/run.invoker',
          'roles/secretmanager.secretAccessor',
          'roles/cloudsql.client',
          'roles/logging.logWriter',
          'roles/monitoring.metricWriter',
        ],
      },
      governance: {
        read_only: true,
        audit_enabled: true,
        pii_redaction: true,
        max_tokens_per_request: 4096,
      },
      created_at: new Date().toISOString(),
    };

    const finalBuildSpan = endSpan(buildSpan, 'ok', {
      registrationId: registration.registration_id,
      endpointCount: endpoints.length,
      connectorType: registration.connector_type,
    });
    emitSpan(finalBuildSpan);
    context.telemetrySpans.push(finalBuildSpan);

    const liveSpan = createSpan(
      'service-registration',
      'attempt-live-registration',
      {},
      rootSpan.spanId,
    );

    // Attempt live push to connector-hub/erp-surface Cloud Function
    let liveResult: { live: boolean; response?: Record<string, unknown>; error?: string } = { live: false };
    try {
      liveResult = await attemptLiveRegistration(registration);
    } catch {
      liveResult = { live: false, error: 'unexpected error' };
    }

    const liveMode = liveResult.live ? 'cloud-registered' : 'local-only';
    const finalLiveSpan = endSpan(liveSpan, 'ok', { mode: liveMode, live: liveResult.live });
    emitSpan(finalLiveSpan);
    context.telemetrySpans.push(finalLiveSpan);

    const writeSpan = createSpan(
      'service-registration',
      'write-registration-artifacts',
      { phase6Dir: context.phase6Dir },
      rootSpan.spanId,
    );

    mkdirSync(context.phase6Dir, { recursive: true, mode: DIR_MODE });

    const writtenPaths: string[] = [];

    const registrationPath = join(context.phase6Dir, 'registration.json');
    writeJsonArtifact(registrationPath, {
      _generated: GENERATED_HEADER,
      ...registration,
      erp_secret_names: authConfig.secretNames,
      erp_env_vars: authConfig.envVars,
      _live_registration: liveResult.live,
      _live_registration_error: liveResult.error ?? null,
    });
    writtenPaths.push(registrationPath);

    const connectorMapping = buildConnectorHubMapping(registration);
    const mappingPath = join(context.phase6Dir, 'erp-surface-mapping.json');
    writeJsonArtifact(mappingPath, connectorMapping);
    writtenPaths.push(mappingPath);

    const finalWriteSpan = endSpan(writeSpan, 'ok', { filesWritten: writtenPaths.length });
    emitSpan(finalWriteSpan);
    context.telemetrySpans.push(finalWriteSpan);

    // Store ERP registration + lineage in Ruvector (non-fatal, fire-and-forget)
    void storeRegistrationInRuvector(context.traceId, registration, endpoints, writtenPaths);

    const finalRootSpan = endSpan(rootSpan, 'ok', {
      registrationId: registration.registration_id,
      serviceName,
      erpSystem,
      erpVendor,
      endpointCount: endpoints.length,
      filesWritten: writtenPaths.length,
      hasSurfaceDefinitions: surfaceDefinitions !== null,
      liveRegistration: liveResult.live,
    });
    emitSpan(finalRootSpan);
    context.telemetrySpans.push(finalRootSpan);

    const timing = Date.now() - startTime;
    const liveStatus = liveResult.live ? 'LIVE' : 'LOCAL-ONLY';
    console.error(`  [ERP] Registration: ${liveStatus} | ${serviceName} → ${erpSystem} | ${endpoints.length} endpoints`);

    const output: Phase6StageOutput = {
      stage: 'service-registration',
      status: 'completed',
      data: {
        registration: {
          ...registration,
          erp_secret_names: authConfig.secretNames,
          erp_env_vars: authConfig.envVars,
        },
        connectorMapping,
        surfaceDefinitions,
        liveRegistration: liveResult.live,
        liveRegistrationError: liveResult.error ?? null,
      },
      artifacts: writtenPaths,
      timing,
    };

    context.stageOutputs.set('service-registration', output);
    return output;
  } catch (err: unknown) {
    const errorMessage = err instanceof Error ? err.message : String(err);

    const finalRootSpan = endSpan(rootSpan, 'error', { error: errorMessage });
    emitSpan(finalRootSpan);
    context.telemetrySpans.push(finalRootSpan);

    const timing = Date.now() - startTime;

    const output: Phase6StageOutput = {
      stage: 'service-registration',
      status: 'failed',
      data: { error: errorMessage },
      artifacts: [],
      timing,
    };

    context.stageOutputs.set('service-registration', output);
    return output;
  }
}


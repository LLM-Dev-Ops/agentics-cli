/**
 * Derive a concise kebab-case service name from the scenario query string.
 * Extracts key domain terms (stripping stop words and verbs) and produces
 * a DNS-safe slug of at most 63 characters.
 *
 * @example "Build a healthcare supply chain optimizer with SAP" -> "healthcare-supply-optimizer"
 * @example "SAP procurement copilot for vendor management" -> "sap-procurement-copilot"
 */
/**
 * Derive a concise kebab-case service name from pipeline artifacts.
 *
 * Priority order:
 *   1. SPARC specification title (LLM already understood the project)
 *   2. DDD model — combine top bounded context names
 *   3. scenario_type from the simulation extraction
 *   4. Keyword extraction from the scenario query (fallback)
 *
 * The earlier phases already processed the user's multi-paragraph prompt
 * through an LLM — use their output instead of regex heuristics.
 */
function deriveServiceName(scenarioQuery: string, runDir?: string): string {
  // ── Strategy 1: Read SPARC spec title or DDD context names from prior phases ──
  if (runDir) {
    // Try SPARC specification — it has a proper project title
    for (const candidate of [
      'phase3/sparc/specification.md',
      'phase2/sparc/specification.md',
    ]) {
      const p = path.join(runDir, candidate);
      if (fs.existsSync(p)) {
        try {
          const content = fs.readFileSync(p, 'utf-8');
          // Look for the first H1 or H2 that isn't just "SPARC Specification" / "Specification"
          const titleMatch = content.match(/^#{1,2}\s+(?!SPARC|Specification|S\s*—)(.+)/m);
          if (titleMatch?.[1]) {
            const title = titleMatch[1].trim().replace(/[*_`]/g, '');
            if (title.length > 5 && title.length < 80) {
              return slugifyName(title);
            }
          }
          // Look for "## Objective" or "### Objective" content
          const objectiveMatch = content.match(/#{2,3}\s+Objective\s*\n+\s*(.+)/m);
          if (objectiveMatch?.[1]) {
            const obj = objectiveMatch[1].trim();
            if (obj.length > 10) {
              return slugifyName(obj.slice(0, 80));
            }
          }
        } catch { /* skip */ }
      }
    }

    // Try DDD model — combine the top 2-3 bounded context names
    for (const candidate of [
      'phase4/ddd/domain-model.json',
      'phase2/ddd/domain-model.json',
    ]) {
      const p = path.join(runDir, candidate);
      if (fs.existsSync(p)) {
        try {
          const model = JSON.parse(fs.readFileSync(p, 'utf-8'));
          const contexts: string[] = (model.contexts ?? [])
            .map((c: Record<string, unknown>) => String(c['name'] ?? ''))
            .filter((n: string) => n.length > 0);
          if (contexts.length >= 2) {
            // Use first 2-3 context names to form the service name
            return slugifyName(contexts.slice(0, 3).join(' '));
          }
        } catch { /* skip */ }
      }
    }

    // Try scenario.json for scenario_type
    const scenarioPath = path.join(runDir, 'scenario.json');
    if (fs.existsSync(scenarioPath)) {
      try {
        const scenario = JSON.parse(fs.readFileSync(scenarioPath, 'utf-8'));
        const scenarioType = scenario['scenario_type'] ?? scenario['type'];
        if (scenarioType && typeof scenarioType === 'string' && scenarioType.length > 3) {
          return slugifyName(scenarioType);
        }
      } catch { /* skip */ }
    }

    // Try manifest.json for scenario_type
    const manifestPath = path.join(runDir, 'manifest.json');
    if (fs.existsSync(manifestPath)) {
      try {
        const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf-8'));
        const scenarioType = manifest['scenario_type'] ?? manifest['domain'];
        if (scenarioType && typeof scenarioType === 'string' && scenarioType.length > 3) {
          return slugifyName(scenarioType);
        }
      } catch { /* skip */ }
    }
  }

  // ── Strategy 2: Domain classification from the query text ──
  const queryLower = scenarioQuery.toLowerCase();
  const DOMAIN_CLASSIFIERS: Array<{ keywords: string[]; name: string }> = [
    { keywords: ['reverse logistics', 'circular economy', 'take-back', 'refurbishment', 'recycling', 'product lifecycle'], name: 'circular-economy-optimizer' },
    { keywords: ['supply chain', 'logistics', 'warehouse', 'inventory', 'procurement'], name: 'supply-chain-platform' },
    { keywords: ['financial', 'accounting', 'revenue', 'billing', 'invoice', 'payment'], name: 'financial-operations' },
    { keywords: ['manufacturing', 'production', 'quality control', 'plant', 'factory'], name: 'manufacturing-ops' },
    { keywords: ['customer', 'crm', 'sales pipeline', 'lead management'], name: 'crm-platform' },
    { keywords: ['compliance', 'audit', 'regulatory', 'governance'], name: 'compliance-engine' },
    { keywords: ['hr', 'human resource', 'workforce', 'talent', 'recruiting', 'attrition'], name: 'workforce-analytics' },
    { keywords: ['monitoring', 'observability', 'alerting', 'telemetry'], name: 'ops-monitoring' },
    { keywords: ['data pipeline', 'etl', 'data warehouse', 'analytics', 'reporting'], name: 'data-analytics' },
    { keywords: ['vendor', 'supplier', 'contract', 'sourcing'], name: 'vendor-management' },
    { keywords: ['security', 'authentication', 'authorization', 'identity'], name: 'security-platform' },
    { keywords: ['healthcare', 'clinical', 'patient', 'medical'], name: 'healthcare-platform' },
    { keywords: ['e-commerce', 'marketplace', 'storefront', 'cart', 'checkout'], name: 'commerce-platform' },
    { keywords: ['real estate', 'property', 'tenant', 'lease'], name: 'property-management' },
  ];

  for (const classifier of DOMAIN_CLASSIFIERS) {
    const matchCount = classifier.keywords.filter(kw => queryLower.includes(kw)).length;
    if (matchCount >= 2) return classifier.name;
  }

  // ── Strategy 3: Fallback — extract key terms from the query ──
  const STOP_WORDS = new Set([
    'the', 'a', 'an', 'and', 'or', 'but', 'in', 'on', 'at', 'to', 'for',
    'of', 'with', 'by', 'from', 'as', 'is', 'was', 'are', 'were', 'be',
    'been', 'being', 'have', 'has', 'had', 'do', 'does', 'did', 'will',
    'would', 'could', 'should', 'may', 'might', 'can', 'shall', 'must',
    'that', 'which', 'who', 'this', 'these', 'those', 'it', 'its',
    'not', 'no', 'if', 'when', 'where', 'how', 'what', 'why',
    'all', 'each', 'every', 'both', 'more', 'most', 'other', 'some',
    'build', 'create', 'make', 'implement', 'develop', 'design', 'use',
    'using', 'want', 'need', 'like', 'help', 'please', 'generate',
    'i', 'we', 'my', 'our', 'me', 'us', 'you', 'your',
    'lead', 'global', 'strategy', 'company', 'approximately', 'employees',
    'operating', 'facilities', 'centers', 'channels', 'across', 'run',
    'one', 'biggest', 'challenges', 'face', 'believe', 'rather',
    'instead', 'however', 'today', 'currently', 'viable', 'working',
    'prototype', 'concept', 'evaluate', 'demonstrates', 'existing',
    'workflows', 'multinational', 'enterprise', 'processes',
  ]);

  const words = queryLower.replace(/[^a-z0-9\s-]/g, ' ').split(/\s+/)
    .filter(w => w.length > 2 && !STOP_WORDS.has(w));

  if (words.length === 0) return 'erp-service';

  // For long prompts, use frequency analysis; for short ones, first words
  if (words.length > 30) {
    const freq = new Map<string, number>();
    for (const w of words) freq.set(w, (freq.get(w) ?? 0) + 1);
    const topTerms = [...freq.entries()]
      .filter(([, count]) => count >= 2)
      .sort((a, b) => b[1] - a[1])
      .map(([word]) => word)
      .slice(0, 4);
    if (topTerms.length >= 2) return topTerms.join('-');
  }

  return words.slice(0, 4).join('-');
}

/** Convert a human-readable title to a DNS-safe kebab-case slug (max 63 chars). */
function slugifyName(title: string): string {
  const slug = title
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, ' ')
    .split(/\s+/)
    .filter(w => w.length > 0)
    .join('-')
    .replace(/-{2,}/g, '-')
    .replace(/^-|-$/g, '');

  if (slug.length <= 63) return slug || 'erp-service';
  const truncated = slug.slice(0, 63);
  const lastDash = truncated.lastIndexOf('-');
  return lastDash > 0 ? truncated.slice(0, lastDash) : truncated;
}


/** Convert string to camelCase for REST API paths. */
function toCamelCase(text: string): string {
  return text
    .replace(/[-_\s]+(.)?/g, (_, c: string | undefined) => (c ? c.toUpperCase() : ''))
    .replace(/^(.)/, (_, c: string) => c.toLowerCase());
}

/**
 * Build endpoint mappings from the DDD domain model, using vendor-specific
 * API conventions. Falls back to generic REST if no DDD model available.
 */
function buildEndpointsFromDomainModel(
  vendor: string,
  phase6Dir: string,
): ERPEndpointMapping[] {
  const vendorConfig = ERP_VENDOR_CONFIG[vendor] ?? ERP_VENDOR_CONFIG['sap']!;
  const endpoints: ERPEndpointMapping[] = [];

  // Try to load the DDD domain model from prior phases
  let contexts: Array<{ name: string; commands?: Array<{ name: string; description?: string }>; queries?: Array<{ name: string }> }> = [];
  const dddPaths = [
    join(phase6Dir, '..', 'phase5', '.phase2-merged', 'ddd', 'domain-model.json'),
    join(phase6Dir, '..', 'phase4', 'ddd', 'domain-model.json'),
    join(phase6Dir, '..', 'phase2', 'ddd', 'domain-model.json'),
  ];
  for (const dddPath of dddPaths) {
    try {
      if (existsSync(dddPath)) {
        const model = JSON.parse(readFileSync(dddPath, 'utf-8'));
        contexts = model.contexts ?? [];
        break;
      }
    } catch { /* continue to next path */ }
  }

  // Generate endpoints from DDD bounded contexts
  if (contexts.length > 0) {
    for (const ctx of contexts) {
      const ctxSlug = ctx.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
      // Command endpoints (POST)
      for (const cmd of (ctx.commands ?? []).slice(0, 4)) {
        const cmdSlug = cmd.name.replace(/([A-Z])/g, '-$1').toLowerCase().replace(/^-/, '').replace(/[^a-z0-9-]/g, '-');
        endpoints.push({
          method: 'POST',
          path: `/api/v1/${ctxSlug}/${cmdSlug}`,
          erp_service: vendorConfig.toService(ctx.name),
          erp_entity: vendorConfig.toEntity(ctx.name),
          description: cmd.description ?? `${cmd.name} for ${ctx.name}`,
        });
      }
      // Query endpoints (GET) — at most 2 per context
      for (const q of (ctx.queries ?? []).slice(0, 2)) {
        const qSlug = q.name.replace(/([A-Z])/g, '-$1').toLowerCase().replace(/^-/, '').replace(/[^a-z0-9-]/g, '-');
        endpoints.push({
          method: 'GET',
          path: `/api/v1/${ctxSlug}/${qSlug}`,
          erp_service: vendorConfig.toService(ctx.name),
          erp_entity: vendorConfig.toEntity(ctx.name),
          description: `${q.name} for ${ctx.name}`,
        });
      }
    }
  }

  // If no DDD model available, generate generic endpoints
  if (endpoints.length === 0) {
    endpoints.push({
      method: 'POST',
      path: '/api/v1/entities/process',
      erp_service: vendorConfig.toService('entity'),
      erp_entity: vendorConfig.toEntity('entity'),
      description: 'Process entity with AI-assisted analysis',
    });
  }

  // Always add operational endpoints
  endpoints.push(
    { method: 'GET', path: '/api/v1/health', erp_service: 'N/A', erp_entity: 'N/A', description: 'Service health check with ERP connectivity probe' },
    { method: 'GET', path: '/api/v1/governance/policies', erp_service: 'N/A', erp_entity: 'N/A', description: 'Return active governance policies and data access controls' },
    { method: 'GET', path: '/api/v1/governance/audit', erp_service: 'N/A', erp_entity: 'N/A', description: 'Retrieve audit trail for all ERP surface interactions' },
  );

  return endpoints;
}


// Helper: Derive service name from scenario query
// ============================================================================

/**
 * Derive a concise kebab-case service name from the scenario query string.
 * Extracts key domain terms (stripping stop words and verbs) and produces
 * a DNS-safe slug of at most 63 characters.
 *
 * @example "Build a healthcare supply chain optimizer with SAP" -> "healthcare-supply-optimizer"
 * @example "SAP procurement copilot for vendor management" -> "sap-procurement-copilot"
 */
function deriveServiceName(scenarioQuery: string): string {
  const SERVICE_STOP_WORDS = new Set([
    'the', 'a', 'an', 'and', 'or', 'but', 'in', 'on', 'at', 'to', 'for',
    'of', 'with', 'by', 'from', 'as', 'is', 'was', 'are', 'were', 'be',
    'been', 'being', 'have', 'has', 'had', 'do', 'does', 'did', 'will',
    'would', 'could', 'should', 'may', 'might', 'can', 'shall', 'must',
    'that', 'which', 'who', 'this', 'these', 'those', 'it', 'its',
    'not', 'no', 'if', 'when', 'where', 'how', 'what', 'why',
    'all', 'each', 'every', 'both', 'more', 'most', 'other', 'some',
    'such', 'than', 'too', 'very', 'just', 'about', 'into', 'through',
    'during', 'without', 'within', 'inside', 'also', 'only', 'then',
    'build', 'create', 'make', 'implement', 'develop', 'design', 'use',
    'using', 'want', 'need', 'like', 'help', 'please', 'generate',
    'i', 'we', 'my', 'our', 'me', 'us', 'you', 'your',
  ]);

  const words = scenarioQuery
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, ' ')
    .split(/\s+/)
    .filter(w => w.length > 1 && !SERVICE_STOP_WORDS.has(w));

  if (words.length === 0) return 'erp-service';

  // Take the first 3-4 meaningful words to form a concise slug
  const slug = words.slice(0, 4).join('-');

  // Enforce DNS label limit (63 chars), truncating at word boundary
  if (slug.length <= 63) return slug;
  const truncated = slug.slice(0, 63);
  const lastDash = truncated.lastIndexOf('-');
  return lastDash > 0 ? truncated.slice(0, lastDash) : truncated;
}

// ============================================================================
// Helper: Resolve ERP vendor from system identifier
// ============================================================================

/**
 * Map an ERP system string to the canonical vendor identifier.
 */
function resolveERPVendor(
  erpSystem: string,
): ERPSurfaceRegistration['erp_vendor'] {
  const normalized = erpSystem.toLowerCase();
  if (normalized.includes('sap')) return 'sap';
  if (normalized.includes('oracle')) return 'oracle';
  if (normalized.includes('dynamics')) return 'dynamics';
  if (normalized.includes('workday')) return 'workday';
  if (normalized.includes('netsuite')) return 'netsuite';
  if (normalized.includes('servicenow')) return 'servicenow';
  return 'sap'; // default for procurement scenarios
}


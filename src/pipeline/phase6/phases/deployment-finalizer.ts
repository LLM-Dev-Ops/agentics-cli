/**
 * Stage 4: Generate production-ready deployment scripts.
 *
 * @param context - The mutable Phase 6 pipeline context
 * @returns Stage output describing success or failure
 */
export function finalizeDeployment(context: Phase6Context): Phase6StageOutput {
  const startTime = Date.now();
  const rootSpan = createSpan('deployment-finalization', 'finalize-deployment', {
    phase6Dir: context.phase6Dir,
    erpSystem: context.phase5Artifacts.erpSystem,
  });

  try {
    const vars = deriveDeploymentVars(context);
    const erpSystem = context.phase5Artifacts.erpSystem;
    const infraRepoPath = resolveInfraRepoPath(context.platformRepoPaths);

    const varsSpan = createSpan('deployment-finalization', 'derive-vars', {}, rootSpan.spanId);
    const finalVarsSpan = endSpan(varsSpan, 'ok', {
      serviceName: vars.serviceName, hasInfraRepo: infraRepoPath !== undefined,
    });
    emitSpan(finalVarsSpan);
    context.telemetrySpans.push(finalVarsSpan);

    const deployDir = join(context.phase6Dir, 'deploy');
    mkdirSync(deployDir, { recursive: true, mode: DIR_MODE });

    const writtenPaths: string[] = [];

    const genSpan = createSpan('deployment-finalization', 'generate-scripts', { deployDir }, rootSpan.spanId);

    writeScript(join(deployDir, 'deploy.sh'), generateDeployScript(vars, erpSystem));
    writtenPaths.push(join(deployDir, 'deploy.sh'));

    writeScript(join(deployDir, 'teardown.sh'), generateTeardownScript(vars));
    writtenPaths.push(join(deployDir, 'teardown.sh'));

    writeArtifact(join(deployDir, 'env.template'), generateEnvTemplate(vars, erpSystem));
    writtenPaths.push(join(deployDir, 'env.template'));

    writeScript(join(deployDir, 'vpc-setup.sh'), generateVpcSetupScript(vars, infraRepoPath));
    writtenPaths.push(join(deployDir, 'vpc-setup.sh'));

    writeArtifact(join(deployDir, 'monitoring.yaml'), generateMonitoringYaml(vars));
    writtenPaths.push(join(deployDir, 'monitoring.yaml'));

    // Generate enterprise README.md for the project root
    const projectDir = join(context.phase6Dir, 'project');
    if (existsSync(projectDir)) {
      const readmeContent = generateReadme(vars, erpSystem, context);
      writeArtifact(join(projectDir, 'README.md'), readmeContent);
      writtenPaths.push(join(projectDir, 'README.md'));
    }

    const finalGenSpan = endSpan(genSpan, 'ok', { filesGenerated: writtenPaths.length });
    emitSpan(finalGenSpan);
    context.telemetrySpans.push(finalGenSpan);

    const finalRootSpan = endSpan(rootSpan, 'ok', {
      serviceName: vars.serviceName, erpSystem, filesGenerated: writtenPaths.length,
    });
    emitSpan(finalRootSpan);
    context.telemetrySpans.push(finalRootSpan);

    const timing = Date.now() - startTime;

    const output: Phase6StageOutput = {
      stage: 'deployment-finalization',
      status: 'completed',
      data: {
        deployDir, serviceName: vars.serviceName, region: vars.region,
        vpcConnector: vars.vpcConnector, filesGenerated: writtenPaths.length,
      },
      artifacts: writtenPaths,
      timing,
    };

    context.stageOutputs.set('deployment-finalization', output);
    return output;
  } catch (err: unknown) {
    const errorMessage = err instanceof Error ? err.message : String(err);

    const finalRootSpan = endSpan(rootSpan, 'error', { error: errorMessage });
    emitSpan(finalRootSpan);
    context.telemetrySpans.push(finalRootSpan);

    const timing = Date.now() - startTime;

    const output: Phase6StageOutput = {
      stage: 'deployment-finalization',
      status: 'failed',
      data: { error: errorMessage },
      artifacts: [],
      timing,
    };

    context.stageOutputs.set('deployment-finalization', output);
    return output;
  }
}

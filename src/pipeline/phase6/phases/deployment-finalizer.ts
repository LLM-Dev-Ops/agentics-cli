/**
 * Phase 6 — Stage 4: Deployment Finalization
 *
 * Generates production-ready deployment scripts:
 * - deploy.sh (gcloud CLI commands)
 * - teardown.sh (cleanup script)
 * - env.template (Secret Manager references)
 * - vpc-setup.sh (VPC connector for ERP network)
 * - monitoring.yaml (Cloud Monitoring alert policies)
 *
 * References infra repo patterns for IAM/networking.
 * References integrations repo for webhook/event patterns.
 */

import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import type { Phase6Context, Phase6StageOutput } from '../types.js';
import { createSpan, endSpan, emitSpan } from '../../phase2/telemetry.js';

// ============================================================================
// Constants
// ============================================================================

const DIR_MODE = 0o700;
const FILE_MODE = 0o600;
const EXEC_MODE = 0o700;

const SCRIPT_HEADER = [
  '#!/usr/bin/env bash',
  '# Generated by Phase 6 pipeline — do not edit manually',
  '#',
  '# This script is deterministic and idempotent.',
  '',
  'set -euo pipefail',
  '',
].join('\n');

// ============================================================================
// Helper: Derive deployment variables from context
// ============================================================================

interface DeploymentVars {
  readonly serviceName: string;
  readonly region: string;
  readonly serviceAccount: string;
  readonly vpcConnector: string;
  readonly erpAuthScheme: string;
  readonly erpSecretNames: readonly string[];
  readonly erpEnvVars: readonly string[];
}

function deriveDeploymentVars(context: Phase6Context): DeploymentVars {
  const registrationStage = context.stageOutputs.get('service-registration');
  let serviceName = 'erp-service';
  let serviceAccount = 'erp-service-sa@PROJECT_ID.iam.gserviceaccount.com';
  let vpcConnector = 'sap-connector';
  let erpAuthScheme = 'api-key';
  let erpSecretNames: readonly string[] = ['erp-api-key'];
  let erpEnvVars: readonly string[] = ['ERP_BASE_URL', 'ERP_API_KEY'];

  if (registrationStage?.status === 'completed' && registrationStage.data) {
    const data = registrationStage.data as Record<string, unknown>;
    const registration = data['registration'] as Record<string, unknown> | undefined;
    if (registration) {
      serviceName = (registration['service_name'] as string) ?? serviceName;
      const vpcConfig = registration['vpc_config'] as Record<string, string> | undefined;
      if (vpcConfig) vpcConnector = vpcConfig['connector_name'] ?? vpcConnector;
      const iamConfig = registration['iam_config'] as Record<string, unknown> | undefined;
      if (iamConfig) serviceAccount = (iamConfig['service_account'] as string) ?? serviceAccount;
      if (registration['auth_scheme']) erpAuthScheme = registration['auth_scheme'] as string;
      if (registration['erp_secret_names']) erpSecretNames = registration['erp_secret_names'] as readonly string[];
      if (registration['erp_env_vars']) erpEnvVars = registration['erp_env_vars'] as readonly string[];
    }
  }

  return { serviceName, region: 'us-central1', serviceAccount, vpcConnector, erpAuthScheme, erpSecretNames, erpEnvVars };
}

// ============================================================================
// Script Generators
// ============================================================================

function generateDeployScript(vars: DeploymentVars, erpSystem: string): string {
  // Build ERP-specific secrets string for --set-secrets
  const secretMappings = vars.erpSecretNames
    .map(name => {
      const envKey = name.toUpperCase().replace(/[^A-Z0-9]/g, '_');
      return `${envKey}=${name}:latest`;
    })
    .join(',');

  return [
    SCRIPT_HEADER,
    `# Deploy ${vars.serviceName} to Cloud Run`,
    `# ERP System: ${erpSystem}`,
    `# Auth Scheme: ${vars.erpAuthScheme}`,
    '',
    'GCP_PROJECT_ID=${GCP_PROJECT_ID:?ERROR: GCP_PROJECT_ID must be set}',
    `GCP_REGION="\${GCP_REGION:-${vars.region}}"`,
    `SERVICE_NAME="\${SERVICE_NAME:-${vars.serviceName}}"`,
    'IMAGE_TAG="${IMAGE_TAG:-latest}"',
    'IMAGE_URL="gcr.io/${GCP_PROJECT_ID}/${SERVICE_NAME}:${IMAGE_TAG}"',
    `SERVICE_ACCOUNT="\${SERVICE_ACCOUNT:-${vars.serviceAccount}}"`,
    `VPC_CONNECTOR="\${VPC_CONNECTOR:-${vars.vpcConnector}}"`,
    '',
    'echo "[1/5] Checking GCP authentication..."',
    'gcloud auth print-identity-token > /dev/null 2>&1 || { echo "Not authenticated."; exit 1; }',
    '',
    'echo "[2/5] Setting project..."',
    'gcloud config set project "${GCP_PROJECT_ID}"',
    '',
    'echo "[3/5] Building container image..."',
    'gcloud builds submit --tag "${IMAGE_URL}" --timeout=600s .',
    '',
    'echo "[4/5] Deploying to Cloud Run..."',
    'gcloud run deploy "${SERVICE_NAME}" \\',
    '  --image "${IMAGE_URL}" \\',
    '  --region "${GCP_REGION}" \\',
    '  --platform managed \\',
    '  --no-allow-unauthenticated \\',
    '  --vpc-connector "${VPC_CONNECTOR}" \\',
    '  --vpc-egress all-traffic \\',
    '  --service-account "${SERVICE_ACCOUNT}" \\',
    ...(secretMappings ? [`  --set-secrets "${secretMappings}" \\`] : []),
    `  --set-env-vars "NODE_ENV=production,PORT=8080,ERP_SYSTEM=${erpSystem}" \\`,
    '  --min-instances 0 --max-instances 10 \\',
    '  --memory 512Mi --cpu 1 --timeout 300 --concurrency 80 \\',
    '  --ingress internal-and-cloud-load-balancing --quiet',
    '',
    'echo "[5/5] Verifying deployment..."',
    'SERVICE_URL=$(gcloud run services describe "${SERVICE_NAME}" --region "${GCP_REGION}" --format "value(status.url)")',
    'echo "Deployed: ${SERVICE_URL}"',
    '',
  ].join('\n');
}

function generateTeardownScript(vars: DeploymentVars): string {
  return [
    SCRIPT_HEADER,
    `# Teardown ${vars.serviceName}`,
    '',
    'GCP_PROJECT_ID=${GCP_PROJECT_ID:?ERROR: GCP_PROJECT_ID must be set}',
    `GCP_REGION="\${GCP_REGION:-${vars.region}}"`,
    `SERVICE_NAME="\${SERVICE_NAME:-${vars.serviceName}}"`,
    '',
    'read -rp "Are you sure you want to delete ${SERVICE_NAME}? (y/N): " CONFIRM',
    'if [[ "${CONFIRM}" != "y" && "${CONFIRM}" != "Y" ]]; then echo "Cancelled."; exit 0; fi',
    '',
    'echo "[1/3] Deleting Cloud Run service..."',
    'gcloud run services delete "${SERVICE_NAME}" --region "${GCP_REGION}" --quiet 2>/dev/null || echo "  Not found."',
    '',
    'echo "[2/3] Cleaning container images..."',
    'gcloud container images list-tags "gcr.io/${GCP_PROJECT_ID}/${SERVICE_NAME}" --format="get(digest)" 2>/dev/null | while read -r DIGEST; do',
    '  gcloud container images delete "gcr.io/${GCP_PROJECT_ID}/${SERVICE_NAME}@${DIGEST}" --quiet --force-delete-tags 2>/dev/null || true',
    'done',
    '',
    'echo "[3/3] Done."',
    '',
  ].join('\n');
}

function generateEnvTemplate(vars: DeploymentVars, erpSystem: string): string {
  const lines = [
    '# Generated by Phase 6 pipeline',
    `# ERP System: ${erpSystem}`,
    `# Auth Scheme: ${vars.erpAuthScheme}`,
    '',
    `GCP_REGION=${vars.region}`,
    `SERVICE_NAME=${vars.serviceName}`,
    `SERVICE_ACCOUNT=${vars.serviceAccount}`,
    'PORT=8080',
    'NODE_ENV=production',
    `ERP_SYSTEM=${erpSystem}`,
    `VPC_CONNECTOR=${vars.vpcConnector}`,
    '',
    '# ERP-specific environment variables',
  ];

  for (const envVar of vars.erpEnvVars) {
    lines.push(`${envVar}=`);
  }

  // Add secret references for each ERP secret
  lines.push('');
  lines.push('# Secret Manager references');
  for (const secretName of vars.erpSecretNames) {
    const envKey = secretName.toUpperCase().replace(/[^A-Z0-9]/g, '_');
    lines.push(`${envKey}=projects/\${GCP_PROJECT_ID}/secrets/${secretName}/versions/latest`);
  }
  lines.push('');

  return lines.join('\n');
}

function generateVpcSetupScript(vars: DeploymentVars, infraRepoPath: string | undefined): string {
  let infraNote = '';
  if (infraRepoPath) {
    infraNote = `# Follows patterns from: ${infraRepoPath}/modules/networking/\n`;
  }
  return [
    SCRIPT_HEADER,
    `# VPC Connector Setup for ${vars.serviceName}`,
    infraNote,
    'GCP_PROJECT_ID=${GCP_PROJECT_ID:?ERROR: GCP_PROJECT_ID must be set}',
    `GCP_REGION="\${GCP_REGION:-${vars.region}}"`,
    `VPC_CONNECTOR="\${VPC_CONNECTOR:-${vars.vpcConnector}}"`,
    '',
    'gcloud services enable vpcaccess.googleapis.com --project "${GCP_PROJECT_ID}" --quiet',
    'gcloud compute networks vpc-access connectors create "${VPC_CONNECTOR}" \\',
    '  --region "${GCP_REGION}" --network default --range 10.8.0.0/28 \\',
    '  --min-instances 2 --max-instances 10 --machine-type e2-micro \\',
    '  --quiet 2>/dev/null || echo "VPC connector already exists."',
    '',
    'echo "VPC setup complete: ${VPC_CONNECTOR}"',
    '',
  ].join('\n');
}

function generateMonitoringYaml(vars: DeploymentVars): string {
  const sn = vars.serviceName;
  return [
    '# Generated by Phase 6 pipeline',
    `# Alert policies for ${sn}`,
    '',
    'alertPolicies:',
    `  - displayName: "[${sn}] High Error Rate"`,
    '    conditions:',
    '      - displayName: "5xx > 5%"',
    '        conditionThreshold:',
    `          filter: resource.labels.service_name="${sn}" AND metric.labels.response_code_class="5xx"`,
    '          comparison: COMPARISON_GT',
    '          thresholdValue: 0.05',
    '          duration: 300s',
    '',
    `  - displayName: "[${sn}] Elevated Latency"`,
    '    conditions:',
    '      - displayName: "p99 > 5s"',
    '        conditionThreshold:',
    `          filter: resource.labels.service_name="${sn}"`,
    '          comparison: COMPARISON_GT',
    '          thresholdValue: 5000',
    '          duration: 300s',
    '',
  ].join('\n');
}

// ============================================================================
// File writers
// ============================================================================

function writeScript(absPath: string, content: string): void {
  writeFileSync(absPath, content, { encoding: 'utf-8', mode: EXEC_MODE });
}

function writeArtifact(absPath: string, content: string): void {
  writeFileSync(absPath, content, { encoding: 'utf-8', mode: FILE_MODE });
}

function resolveInfraRepoPath(platformRepoPaths: Record<string, string>): string | undefined {
  const infraPath = platformRepoPaths['infra'];
  if (!infraPath || !existsSync(infraPath)) return undefined;
  return infraPath;
}


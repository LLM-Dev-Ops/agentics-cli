function generateReadme(vars: DeploymentVars, erpSystem: string, context: Phase6Context): string {
  const serviceName = vars.serviceName;
  const serviceNameUpper = serviceName.replace(/-/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
  const scenario = context.scenarioQuery ?? '';

  // ── Load ADRs and DDD model from pipeline artifacts for solution description ──
  const runDir = path.dirname(context.phase6Dir);
  let adrs: Array<{ id: string; title: string; context: string; decision: string }> = [];
  let dddContexts: Array<{ name: string; description: string; aggregates: Array<{ name: string; root: string }>; commands: string[]; queries: string[]; domainEvents: string[] }> = [];

  // Load ADRs
  for (const candidate of ['phase4/adrs/adr-index.json', 'phase2/adrs/adr-index.json']) {
    const p = path.join(runDir, candidate);
    if (fs.existsSync(p)) {
      try { adrs = JSON.parse(fs.readFileSync(p, 'utf-8')); break; } catch { /* skip */ }
    }
  }

  // Load DDD model
  for (const candidate of ['phase4/ddd/domain-model.json', 'phase2/ddd/domain-model.json']) {
    const p = path.join(runDir, candidate);
    if (fs.existsSync(p)) {
      try {
        const model = JSON.parse(fs.readFileSync(p, 'utf-8'));
        dddContexts = model.contexts ?? [];
        break;
      } catch { /* skip */ }
    }
  }

  // ── Extract a meaningful description from the scenario query ──
  // Take the first ~3 sentences that describe the problem/solution, skip preamble
  const scenarioDescription = extractSolutionDescription(scenario);

  const lines: string[] = [];

  // Title and badges
  lines.push(
    `# ${serviceNameUpper}`,
    '',
    `![TypeScript](https://img.shields.io/badge/TypeScript-5.x-blue.svg)`,
    `![ERP](https://img.shields.io/badge/ERP-${encodeURIComponent(erpSystem)}-orange.svg)`,
    `![Generated](https://img.shields.io/badge/generated_by-Agentics_Pipeline-blueviolet.svg)`,
    '',
  );

  // Overview — use the actual scenario context
  lines.push('## Overview', '');
  if (scenarioDescription) {
    lines.push(scenarioDescription, '');
  } else {
    lines.push(`**${serviceNameUpper}** — an enterprise service integrating with **${erpSystem}**.`, '');
  }
  lines.push(`This service was generated by the Agentics CLI pipeline using SPARC methodology, domain-driven design, and London School TDD.`, '');

  // Key Architecture Decisions (from actual ADRs)
  if (adrs.length > 0) {
    lines.push('## Key Architecture Decisions', '');
    for (const adr of adrs.slice(0, 10)) {
      lines.push(`- **${adr.title}** — ${adr.decision?.slice(0, 200) ?? adr.context?.slice(0, 200) ?? 'See ADR document'}`);
    }
    lines.push('', `> Full ADR documentation in \`.agentics/plans/adrs/\``, '');
  }

  // Domain Model (from actual DDD bounded contexts)
  if (dddContexts.length > 0) {
    lines.push('## Domain Model', '');
    lines.push(`The system is organized into **${dddContexts.length} bounded contexts**:`, '');
    for (const ctx of dddContexts) {
      const details: string[] = [];
      if (ctx.aggregates?.length) details.push(`${ctx.aggregates.length} aggregates`);
      if (ctx.commands?.length) details.push(`${ctx.commands.length} commands`);
      if (ctx.queries?.length) details.push(`${ctx.queries.length} queries`);
      if (ctx.domainEvents?.length) details.push(`${ctx.domainEvents.length} events`);
      const detailStr = details.length > 0 ? ` (${details.join(', ')})` : '';
      lines.push(`### ${ctx.name}${detailStr}`, '');
      if (ctx.description) lines.push(ctx.description, '');
    }
  }

  // Project structure
  lines.push(
    '## Project Structure', '',
    '```',
    'src/',
    '├── contexts/              # Bounded contexts (DDD)',
  );
  if (dddContexts.length > 0) {
    for (const ctx of dddContexts.slice(0, 5)) {
      const slug = ctx.name.toLowerCase().replace(/[^a-z0-9]+/g, '-');
      lines.push(`│   ├── ${slug}/`);
    }
  } else {
    lines.push('│   └── <context>/');
  }
  lines.push(
    '├── server/                # HTTP API (Hono.js)',
    '├── middleware/             # Validation, auth, health',
    '├── integrations/          # ERP client & event mapping',
    '└── di/                    # Dependency injection',
    '```', '',
  );

  // Quick Start
  lines.push(
    '## Quick Start', '',
    '```bash',
    'npm install',
    'npm run build',
    'npm start',
    '```', '',
  );

  // API Endpoints — only show a summary, not 60 rows of [object Object]
  const registrationStage = context.stageOutputs.get('service-registration');
  const registration = registrationStage?.data as Record<string, unknown> | undefined;
  const registrationData = registration?.['registration'] as Record<string, unknown> | undefined;
  const rawEndpoints = (registrationData?.['endpoints'] ?? []) as ReadonlyArray<string | { method?: string; path?: string; erp_service?: string }>;
  const endpoints = rawEndpoints.map(ep => {
    if (typeof ep === 'string') return { method: 'POST', path: ep, erp_service: '' };
    return { method: ep.method ?? 'POST', path: ep.path ?? String(ep), erp_service: ep.erp_service ?? '' };
  });

  lines.push('## API Endpoints', '', '| Method | Path | Description |', '|--------|------|-------------|');
  lines.push('| GET | `/health` | Health check and readiness probe |');
  if (endpoints.length > 0 && endpoints.length <= 20) {
    for (const ep of endpoints) {
      lines.push(`| ${ep.method} | \`${ep.path}\` | ${ep.erp_service ? `${ep.erp_service} endpoint` : 'Domain endpoint'} |`);
    }
  } else if (endpoints.length > 20) {
    // Too many endpoints — show summary instead of a wall of rows
    for (const ep of endpoints.slice(0, 10)) {
      lines.push(`| ${ep.method} | \`${ep.path}\` | ${ep.erp_service ? `${ep.erp_service} endpoint` : 'Domain endpoint'} |`);
    }
    lines.push(`| ... | ... | *${endpoints.length - 10} more endpoints — see route definitions* |`);
  } else {
    lines.push('| POST | `/api/commands/:command` | Execute domain command |');
    lines.push('| GET | `/api/queries/:query` | Execute domain query |');
  }
  lines.push('');

  // ERP Integration
  lines.push(
    '## ERP Integration', '',
    `| Property | Value |`,
    `|----------|-------|`,
    `| ERP System | ${erpSystem} |`,
    `| Auth Scheme | ${vars.erpAuthScheme} |`,
    `| Region | ${vars.region} |`,
    '',
  );

  // Environment Variables
  lines.push('## Environment Variables', '', '| Variable | Description | Required |', '|----------|-------------|----------|');
  lines.push('| `PORT` | Server port (default: 8080) | No |');
  lines.push('| `NODE_ENV` | Environment (production/development) | Yes |');
  lines.push(`| \`ERP_SYSTEM\` | ERP system identifier (${erpSystem}) | Yes |`);
  for (const v of vars.erpEnvVars) {
    lines.push(`| \`${v}\` | ERP connection variable | Yes |`);
  }
  lines.push('');

  // Deployment
  lines.push(
    '## Deployment', '',
    '```bash',
    `docker build -t ${serviceName} .`,
    `docker run -p 8080:8080 --env-file .env ${serviceName}`,
    '```', '',
  );

  // Testing
  lines.push(
    '## Testing', '',
    '```bash',
    'npm test              # Run all tests',
    'npm run test:coverage # With coverage',
    '```', '',
  );

  // Footer
  lines.push(
    '---', '',
    `*Generated on ${new Date().toISOString().split('T')[0]} by [Agentics CLI](https://platform.agentics.dev)*`,
    '',
    '> Pipeline documentation: `.agentics/plans/`',
    '',
  );

  return lines.join('\n');
}

/**
 * Extract a meaningful solution description from the scenario query.
 * Skips "I lead..." / "We are..." preamble and finds the sentences that
 * describe what the system should actually do.
 */
function extractSolutionDescription(scenario: string): string {
  if (!scenario) return '';

  const sentences = scenario
    .replace(/\n+/g, ' ')
    .split(/(?<=[.!?])\s+/)
    .filter(s => s.trim().length > 10);

  // Skip sentences that are preamble (first-person context, company description)
  const preamblePatterns = [
    /^I\s+(lead|manage|am|work|run)\b/i,
    /^We\s+(are|have|believe|face|collect|want)\b/i,
    /^Our\s+(finance|company|team|org)/i,
    /^One\s+of\s+the\s+biggest/i,
    /^Today,?\s+these/i,
    /^However,?\s/i,
    /^If\s+viable/i,
    /^If\s+this\s+concept/i,
    /^Because\s+these/i,
    /^Rather\s+than/i,
    /^This\s+should\s+be\s+implemented/i,
  ];

  // Find sentences that describe what the system should do
  const systemPatterns = [
    /system\s+should/i,
    /AI\s+could/i,
    /model\s+the/i,
    /simulate/i,
    /quantif/i,
    /recommend/i,
    /evaluat/i,
    /optim/i,
    /prototype\s+that/i,
    /produce\s+structured/i,
    /dynamically/i,
  ];

  // Collect good descriptive sentences
  const goodSentences: string[] = [];
  for (const s of sentences) {
    const isPreamble = preamblePatterns.some(p => p.test(s.trim()));
    const isSystem = systemPatterns.some(p => p.test(s));

    if (isSystem && !isPreamble) {
      goodSentences.push(s.trim());
    }
    if (goodSentences.length >= 4) break;
  }

  // If we found system-describing sentences, use them
  if (goodSentences.length > 0) {
    return goodSentences.join(' ');
  }

  // Fallback: skip first 2 preamble sentences, take next 3
  const nonPreamble = sentences.filter(s => !preamblePatterns.some(p => p.test(s.trim())));
  return nonPreamble.slice(0, 3).join(' ').slice(0, 800);
}


/** Candidate directories to search for `.tmpl` files, in priority order. */
function candidateDirs(): string[] {
  const dirs: string[] = [];
  try {
    const here = path.dirname(fileURLToPath(import.meta.url));
    dirs.push(here);
  } catch {
    // import.meta.url may be unavailable in some bundled contexts.
  }
  dirs.push(path.join(process.cwd(), 'src', 'pipeline', 'scaffolds'));
  dirs.push(path.join(process.cwd(), 'dist', 'pipeline', 'scaffolds'));
  return dirs;
}

/**
 * Load a raw scaffold template by filename (e.g. `rust-domain-lib.rs.tmpl`).
 * Prefers the on-disk `.tmpl`; falls back to the embedded copy.
 */
export function loadTemplate(name: string): string {
  for (const dir of candidateDirs()) {
    const candidate = path.join(dir, name);
    try {
      if (fs.statSync(candidate).isFile()) {
        return fs.readFileSync(candidate, 'utf-8');
      }
    } catch {
      // try next candidate
    }
  }
  const embedded = EMBEDDED_TEMPLATES[name];
  if (embedded !== undefined) return embedded;
  throw new Error(`Scaffold template not found: ${name}`);
}

/**
 * Render a template, substituting every `{{key}}` for which `vars[key]` is
 * provided. Unprovided placeholders are left intact so omissions are visible.
 */
export function renderTemplate(name: string, vars: Record<string, string>): string {
  let out = loadTemplate(name);
  for (const [key, value] of Object.entries(vars)) {
    out = out.split(`{{${key}}}`).join(value);
  }
  return out;
}

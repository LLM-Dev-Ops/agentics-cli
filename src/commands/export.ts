function generateKubernetesArtifacts(targetId: string): ExportArtifact[] {
  const namespace = `apiVersion: v1
kind: Namespace
metadata:
  name: agentics-${targetId}
  labels:
    managed-by: agentics-cli
    target-id: "${targetId}"
`;

  const deployment = `apiVersion: apps/v1
kind: Deployment
metadata:
  name: agentics-app
  namespace: agentics-${targetId}
  labels:
    app: agentics
    target-id: "${targetId}"
spec:
  replicas: 1
  selector:
    matchLabels:
      app: agentics
  template:
    metadata:
      labels:
        app: agentics
    spec:
      containers:
      - name: app
        image: placeholder:latest
        ports:
        - containerPort: 8080
        env:
        - name: TARGET_ID
          value: "${targetId}"
        - name: DEPLOYMENT_TIME
          value: "${new Date().toISOString()}"
        resources:
          limits:
            cpu: "500m"
            memory: "512Mi"
          requests:
            cpu: "250m"
            memory: "256Mi"
`;

  const service = `apiVersion: v1
kind: Service
metadata:
  name: agentics-service
  namespace: agentics-${targetId}
spec:
  selector:
    app: agentics
  ports:
  - port: 80
    targetPort: 8080
  type: ClusterIP
`;

  const configMap = `apiVersion: v1
kind: ConfigMap
metadata:
  name: agentics-config
  namespace: agentics-${targetId}
data:
  TARGET_ID: "${targetId}"
  GENERATED_AT: "${new Date().toISOString()}"
  MANAGED_BY: "agentics-cli"
`;

  return [
    { filename: 'namespace.yaml', content: namespace, type: 'kubernetes' },
    { filename: 'deployment.yaml', content: deployment, type: 'kubernetes' },
    { filename: 'service.yaml', content: service, type: 'kubernetes' },
    { filename: 'configmap.yaml', content: configMap, type: 'kubernetes' },
  ];
}

